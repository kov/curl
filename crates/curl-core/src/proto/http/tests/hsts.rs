//! The HSTS cache in transfers (`lib/hsts.c`, `hsts_upgrade`,
//! `http_header_s`): read from files and the application as a transfer
//! starts, an `http` URL to a host in it switched to `https`, a response
//! over HTTPS kept, and the cache written to a file and the application
//! as the handle goes.

use std::sync::Mutex;

use curl_alloc::TryArc;

use super::*;
use crate::hsts::{BadEntry, HstsEntry, HstsRead, HstsReader, HstsWrite, HstsWriter};
use crate::save::CacheFile;
use crate::tls::fake::{self, WELCOME};

/// The time the tests' clock says, 2024-10-09 09:25:47 UTC.
const NOW: i64 = 1_728_465_947;

/// A temporary file of the test's, removed as it goes.
struct Temp(std::path::PathBuf);

impl Temp {
    fn new(name: &str, text: &str) -> Temp {
        let path =
            std::env::temp_dir().join(format!("curl-core-hsts-{name}-{}", std::process::id()));
        std::fs::write(&path, text).unwrap();
        Temp(path)
    }

    fn name(&self) -> &[u8] {
        self.0.as_os_str().as_encoded_bytes()
    }

    fn text(&self) -> String {
        std::fs::read_to_string(&self.0).unwrap()
    }
}

impl Drop for Temp {
    fn drop(&mut self) {
        let _gone = std::fs::remove_file(&self.0);
    }
}

/// A multi whose network knows `sts.example` as 127.0.0.1, where a server
/// says `replies` in turn, and whose clock says `NOW`.
fn named_server(replies: &[&[u8]]) -> (Multi, Conversation) {
    let clock = ManualClock::new().unwrap();
    clock.set_unix_time(NOW);
    let at = SocketAddr::from(([127, 0, 0, 1], PORT));
    let talk = Conversation::replies(replies, false);
    let net = FakeNet::new(clock.clone())
        .with_peer(at, Peer::Accepts)
        .with_conversation(at, talk.clone())
        .with_name("sts.example", &[[127, 0, 0, 1].into()]);
    let env = Env {
        clock: Box::new(clock),
        net: Box::new(net),
        arena: ArenaPolicy::new(16, 0).unwrap(),
        waker: None,
    };
    (Multi::new(env).unwrap(), talk)
}

/// An `http` URL to a host the cache names goes as `https`, the URL read
/// back the transfer's; and what the response over HTTPS says is kept,
/// and written back as the handle goes, to the file it was read from.
#[test]
fn an_http_url_to_a_host_kept_goes_over_https() {
    let file = Temp::new("upgrade", "sts.example \"99991001 04:47:41\"\n");
    let (_backend, libraries) = super::tls::tls();
    let response = b"HTTP/1.1 200 OK\r\nStrict-Transport-Security: max-age=100; \
        includeSubDomains\r\nContent-Length: 3\r\n\r\nok\n";
    let (mut m, talk) = named_server(&[WELCOME, &fake::records(response).unwrap()]);
    let mut e = Easy::new();
    e.set_libraries(libraries);
    e.add_hsts_file(Some(file.name())).unwrap();
    let url = format!("http://sts.example:{PORT}/a");
    let mut ran = get_with(&mut m, e, "/a", talk, |o| {
        o.set_url(Some(url.as_bytes())).unwrap();
    });
    assert_eq!(ran.result, Ok(()));
    let switched =
        format!("Switched from HTTP to HTTPS due to HSTS => https://sts.example:{PORT}/a\n");
    assert!(ran.seen.text().contains(&switched), "{:?}", ran.seen.text());
    let effective = ran.easy.report().url().map(<[u8]>::to_vec);
    assert_eq!(
        effective,
        Some(format!("https://sts.example:{PORT}/a").into_bytes())
    );
    ran.easy.save_hsts().unwrap();
    assert_eq!(
        file.text(),
        "# Your HSTS cache. https://curl.se/docs/hsts.html\n\
         # This file was generated by libcurl! Edit at your own risk.\n\
         .sts.example \"20241009 09:27:27\"\n"
    );
}

/// Over plain HTTP the field is not taken (RFC 6797 8.1), and a URL to a
/// host the cache does not name goes as it is.
#[test]
fn a_field_over_http_is_passed_over() {
    let file = Temp::new("plain", "");
    let response = b"HTTP/1.1 200 OK\r\nStrict-Transport-Security: max-age=100\r\n\
        Content-Length: 3\r\n\r\nok\n";
    let (mut m, talk) = named_server(&[response]);
    let mut e = Easy::new();
    e.add_hsts_file(Some(file.name())).unwrap();
    let url = format!("http://sts.example:{PORT}/a");
    let mut ran = get_with(&mut m, e, "/a", talk, |o| {
        o.set_url(Some(url.as_bytes())).unwrap();
    });
    assert_eq!(ran.result, Ok(()));
    assert!(!ran.seen.text().iter().any(|l| l.starts_with("Switched")));
    ran.easy.save_hsts().unwrap();
    assert!(!file.text().contains("sts.example"), "{}", file.text());
}

/// Gives the entries it holds, then says it is done, or what `last` says.
struct Giving {
    entries: Mutex<Vec<(&'static str, &'static str, bool)>>,
    last: HstsRead,
}

impl HstsReader for Giving {
    fn read(
        &self,
        keep: &mut dyn FnMut(HstsEntry<'_>) -> Result<(), BadEntry>,
    ) -> Result<HstsRead, BadEntry> {
        let next = self.entries.lock().unwrap().pop();
        let Some((name, expire, subdomains)) = next else {
            return Ok(self.last);
        };
        keep(HstsEntry {
            name: name.as_bytes(),
            expire: expire.as_bytes(),
            subdomains,
        })?;
        Ok(HstsRead::Given)
    }
}

/// An entry as a writer is given it: its name, date and reach, its place
/// and the number of entries.
type Taken = (String, String, bool, usize, usize);

/// Keeps what it is given, stopping after `stop_after`.
#[derive(Default)]
struct Taking {
    taken: Mutex<Vec<Taken>>,
    stop_after: Option<usize>,
}

impl HstsWriter for Taking {
    fn write(&self, entry: HstsEntry<'_>, index: usize, total: usize) -> HstsWrite {
        let text = |b: &[u8]| String::from_utf8_lossy(b).into_owned();
        self.taken.lock().unwrap().push((
            text(entry.name),
            text(entry.expire),
            entry.subdomains,
            index,
            total,
        ));
        match self.stop_after {
            Some(n) if index + 1 >= n => HstsWrite::Stop,
            _ => HstsWrite::More,
        }
    }
}

/// The application's reader is read as a transfer starts, an empty date
/// never expiring; its writer is given every entry, its place and the
/// number of them, as the handle is saved, until it says to stop.
#[test]
fn the_application_reads_and_writes_the_cache() {
    let reader = Giving {
        entries: Mutex::new(vec![
            ("never.example", "", false),
            ("gone.example", "20011001 04:47:41", false),
            ("sts.example", "99991001 04:47:41", true),
        ]),
        last: HstsRead::Done,
    };
    let writer = TryArc::try_new(Taking::default()).unwrap();
    struct Shared(TryArc<Taking>);
    impl HstsWriter for Shared {
        fn write(&self, entry: HstsEntry<'_>, index: usize, total: usize) -> HstsWrite {
            self.0.write(entry, index, total)
        }
    }
    let (mut m, talk) = named_server(&[OK]);
    let mut e = Easy::new();
    e.enable_hsts(CacheFile::ReadWrite).unwrap();
    let url = format!("http://sts.example:{PORT}/a");
    let mut ran = get_with(&mut m, e, "/a", talk, |o| {
        o.set_url(Some(url.as_bytes())).unwrap();
        let hsts = o.http.hsts.make_mut().unwrap();
        hsts.read = Some(Handler::hsts_reader(reader).unwrap());
        hsts.write = Some(Handler::hsts_writer(Shared(writer.clone())).unwrap());
    });
    // Switched to https, which a handle without TLS has no protocol for.
    assert_eq!(ran.result, Err(ErrorKind::UnsupportedProtocol));
    assert!(
        ran.seen
            .text()
            .iter()
            .any(|l| l.starts_with("Switched from HTTP to HTTPS"))
    );
    ran.easy.save_hsts().unwrap();
    assert_eq!(
        *writer.taken.lock().unwrap(),
        [
            ("sts.example".into(), "99991001 04:47:41".into(), true, 0, 2),
            ("never.example".into(), "unlimited".into(), false, 1, 2),
        ]
    );
}

/// A reader that says to fail fails the transfer as aborted, and one
/// that gives what no entry is as a bad argument, before anything goes.
#[test]
fn a_reader_s_failure_fails_the_transfer() {
    for (last, kind) in [
        (HstsRead::Abort, ErrorKind::AbortedByCallback),
        (HstsRead::Invalid, ErrorKind::BadFunctionArgument),
    ] {
        let (mut m, talk) = named_server(&[OK]);
        let mut e = Easy::new();
        e.enable_hsts(CacheFile::ReadWrite).unwrap();
        let reader = Giving {
            entries: Mutex::new(Vec::new()),
            last,
        };
        let ran = get_with(&mut m, e, "/a", talk, |o| {
            o.http.hsts.make_mut().unwrap().read = Some(Handler::hsts_reader(reader).unwrap());
        });
        assert_eq!(ran.result, Err(kind));
        assert!(ran.request.is_empty());
    }
}

/// A copy of the handle starts with the entries alive in the original,
/// after what its file and reader give (`curl_easy_duphandle`); the
/// files named are not the copy's.
#[test]
fn a_copy_of_the_handle_keeps_the_entries_alive() {
    let file = Temp::new("copy", "");
    let mut e = Easy::new();
    e.add_hsts_file(Some(file.name())).unwrap();
    let hsts = e.hsts_mut().unwrap();
    let now = crate::time::SystemClock::new().unix_time();
    hsts.parse(b"kept.example", b"max-age=1000", now).unwrap();
    let copy = e.try_clone().unwrap();
    assert!(copy.hsts().is_some_and(|h| h.files_to_read() == 0));
    let mut copy = copy;
    copy.save_hsts().unwrap();
    assert!(file.text().contains("\nkept.example \""), "{}", file.text());
    let off = Easy::new().try_clone().unwrap();
    assert!(!off.hsts_enabled());
}

/// A cache whose file is read-only reads it and never writes it back,
/// nor does a copy of the handle (`CURLHSTS_READONLYFILE`). C tests the
/// flag but never sets it, so writes the file back (DIVERGENCE.md).
#[test]
fn a_read_only_file_is_not_written_back() {
    let text = "# kept as it is\n";
    let file = Temp::new("read-only", text);
    let mut e = Easy::new();
    e.enable_hsts(CacheFile::ReadOnly).unwrap();
    e.add_hsts_file(Some(file.name())).unwrap();
    let hsts = e.hsts_mut().unwrap();
    let now = crate::time::SystemClock::new().unix_time();
    hsts.parse(b"kept.example", b"max-age=1000", now).unwrap();
    let mut copy = e.try_clone().unwrap();
    copy.save_hsts().unwrap();
    e.save_hsts().unwrap();
    assert_eq!(file.text(), text);
    // Enabled again without the flag, it is written back.
    e.enable_hsts(CacheFile::ReadWrite).unwrap();
    e.save_hsts().unwrap();
    assert!(file.text().contains("\nkept.example \""), "{}", file.text());
}
