//! The cache alone: C's unit tests 1654 and 1669, and what they leave
//! out.

use super::*;

/// The time unit1654 runs at (`CURL_TIME`), 2019-01-24 22:34:21 UTC.
const NOW: i64 = 1_548_369_261;

/// A temporary file of the test's, removed as it goes.
struct Temp(std::path::PathBuf);

impl Temp {
    fn new(name: &str, text: &[u8]) -> Temp {
        let path =
            std::env::temp_dir().join(format!("curl-core-altsvc-{name}-{}", std::process::id()));
        std::fs::write(&path, text).unwrap();
        Temp(path)
    }

    fn name(&self) -> &[u8] {
        self.0.as_os_str().as_encoded_bytes()
    }
}

impl Drop for Temp {
    fn drop(&mut self) {
        let _gone = std::fs::remove_file(&self.0);
    }
}

fn parse(a: &mut AltSvc, value: &str, host: &str, port: u16, alpn: Alpn) -> Vec<String> {
    let mut said = Vec::new();
    a.parse(
        value.as_bytes(),
        (host.as_bytes(), port, alpn),
        NOW,
        &mut |args| said.push(args.to_string()),
    )
    .unwrap();
    said
}

const ALL: Versions = Versions {
    h1: true,
    h2: true,
    h3: true,
};

/// unit1654: a file read, fields parsed, a lookup, and the file written.
#[test]
fn unit1654() {
    let file = Temp::new(
        "1654",
        b"h2 example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n\
          h2 expired.com 443 h3 shiny.example.com 8443 \"20190122 00:00:00\" 0 0\n\
          # a comment\n\
          h2 foo.example.com 443 h3 shiny.example.com 8443 \"20291231 23:30:00\" 0 0\n\
          \x20 h1 example.com 443 h3 shiny.example.com 8443 \"20221231 00:00:01\" 0 0\n\
          \th3 example.com 443 h3 shiny.example.com 8443 \"20231231 00:00:00\" 0 0\n\
          \x20   # also a comment\n\
          bad example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n\
          rubbish\n",
    );
    let mut a = AltSvc::default();
    a.load(file.name(), NOW).unwrap();
    assert_eq!(a.len(), 4);
    let h1 = Alpn::H1;
    let h2 = Alpn::H2;
    parse(
        &mut a,
        "h2=\"example.com:8080\"\r\n",
        "example.org",
        8080,
        h1,
    );
    assert_eq!(a.len(), 5);
    parse(&mut a, "h3=\":8080\"\r\n", "2.example.org", 8080, h1);
    assert_eq!(a.len(), 6);
    let v = "h2=\"example.com:8080\", h3=\"yesyes.com:8080\"\r\n";
    parse(&mut a, v, "3.example.org", 8080, h1);
    assert_eq!(a.len(), 8);
    parse(
        &mut a,
        "h2=\"example.com:443\"; ma = 120;\r\n",
        "example.org",
        80,
        h2,
    );
    assert_eq!(a.len(), 9);
    parse(
        &mut a,
        "h2=\"example.net:443\"; ma=\"180\";\r\n",
        "example.net",
        80,
        h2,
    );
    assert_eq!(a.len(), 10);
    let v = "h2=\":443\"; ma=180, h3=\":443\"; persist = \"1\"; ma = 120;\r\n";
    parse(&mut a, v, "curl.se", 80, h1);
    assert_eq!(a.len(), 12);
    parse(&mut a, "clear;\r\n", "curl.se", 80, h1);
    assert_eq!(a.len(), 10);
    let v = "h2=\":443\", h3=\":443\"; persist = \"1\"; ma = 120;\r\n";
    parse(&mut a, v, "curl.se", 80, h1);
    assert_eq!(a.len(), 12);
    parse(&mut a, "clear\r\n", "curl.se", 80, h1);
    assert_eq!(a.len(), 10);
    // A version not known, a missing quote, a missing port and one too
    // large add nothing.
    parse(
        &mut a,
        "h6=\"example.net:443\"; ma=\"180\";\r\n",
        "5.example.net",
        80,
        h2,
    );
    parse(
        &mut a,
        "h2=\"example.net:443,; ma=\"180\";\r\n",
        "6.example.net",
        80,
        h2,
    );
    parse(
        &mut a,
        "h2=\"example.net\"; ma=\"180\";\r\n",
        "7.example.net",
        80,
        h2,
    );
    let said = parse(
        &mut a,
        "h2=\"example.net:70000\"; ma=\"180\";\r\n",
        "8.example.net",
        80,
        h2,
    );
    assert_eq!(said, ["Unknown alt-svc port number, ignoring."]);
    assert_eq!(a.len(), 10);
    let v = "h2=\"test2.se:443\"; ma=\"180 \" ; unknown=2, h2=\"test3.se:443\"; ma = 120;\r\n";
    parse(&mut a, v, "test.se", 443, h2);
    // Unknown parameters do not hide later known ones.
    let v = "h2=\":443\"; long-extension-parameter=token; ext=token; \
             quoted=\"a;\\\"b\"; ma=120; persist=1\r\n";
    parse(&mut a, v, "params.example", 443, h1);
    let versions = Versions {
        h1: false,
        h2: true,
        h3: false,
    };
    let found = a
        .lookup((b"params.example", 443, h1), versions, NOW)
        .unwrap();
    assert!(found.same);
    let e = a.entries.last().unwrap();
    assert_eq!(e.expires, NOW + 120);
    assert!(e.persist);
    parse(&mut a, "clear\r\n", "params.example", 443, h1);
    let text = a.text().unwrap();
    assert_eq!(
        String::from_utf8(text).unwrap(),
        "# Your alt-svc cache. https://curl.se/docs/alt-svc.html\n\
         # This file was generated by libcurl! Edit at your own risk.\n\
         h2 example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n\
         h2 foo.example.com 443 h3 shiny.example.com 8443 \"20291231 23:30:00\" 0 0\n\
         h1 example.com 443 h3 shiny.example.com 8443 \"20221231 00:00:01\" 0 0\n\
         h3 example.com 443 h3 shiny.example.com 8443 \"20231231 00:00:00\" 0 0\n\
         h1 example.org 8080 h2 example.com 8080 \"20190125 22:34:21\" 0 0\n\
         h1 2.example.org 8080 h3 2.example.org 8080 \"20190125 22:34:21\" 0 0\n\
         h1 3.example.org 8080 h2 example.com 8080 \"20190125 22:34:21\" 0 0\n\
         h1 3.example.org 8080 h3 yesyes.com 8080 \"20190125 22:34:21\" 0 0\n\
         h2 example.org 80 h2 example.com 443 \"20190124 22:36:21\" 0 0\n\
         h2 example.net 80 h2 example.net 443 \"20190124 22:37:21\" 0 0\n\
         h2 test.se 443 h2 test2.se 443 \"20190124 22:37:21\" 0 0\n\
         h2 test.se 443 h2 test3.se 443 \"20190124 22:36:21\" 0 0\n"
    );
}

/// unit1669: a file of more entries than the cache keeps keeps the most.
#[test]
fn unit1669() {
    let mut text = Vec::new();
    for n in 0..5010 {
        let line = format!("h2 host{n}.example 443 h3 alt.example 443 \"20391231 00:00:00\" 0 0\n");
        text.extend_from_slice(line.as_bytes());
    }
    let file = Temp::new("1669", &text);
    let mut a = AltSvc::default();
    a.load(file.name(), NOW).unwrap();
    assert_eq!(a.len(), MAX_ENTRIES);
    // The oldest went.
    assert_eq!(a.entries[0].src.host, b"host10.example");
}

/// A lookup finds the first alternative of the origin to a version
/// allowed, drops those expired as it passes them, and tells whether it
/// is the origin's own host and port; the host's one trailing dot and
/// case do not matter.
#[test]
fn a_lookup_finds_the_first_allowed_alternative() {
    let mut a = AltSvc::default();
    parse(
        &mut a,
        "h3=\"alt3:1\", h1=\"Alt1:2\"",
        "origin",
        80,
        Alpn::H1,
    );
    let built = AltSvcCtrl::DEFAULT.versions;
    let found = a.lookup((b"ORIGIN.", 80, Alpn::H1), built, NOW).unwrap();
    assert_eq!(
        (found.host, found.port, found.alpn),
        (&b"Alt1"[..], 2, Alpn::H1)
    );
    assert!(!found.same);
    let found = a.lookup((b"origin", 80, Alpn::H1), ALL, NOW).unwrap();
    assert_eq!(found.host, b"alt3");
    assert!(a.lookup((b"origin", 81, Alpn::H1), ALL, NOW).is_none());
    assert!(a.lookup((b"origin", 80, Alpn::H2), ALL, NOW).is_none());
    // A day later, both have expired, and go.
    assert!(
        a.lookup((b"origin", 80, Alpn::H1), ALL, NOW + 86401)
            .is_none()
    );
    assert!(a.is_empty());
    // A field's alternatives replace those an earlier field gave.
    parse(&mut a, "h1=\"first:1\"", "origin", 80, Alpn::H1);
    parse(&mut a, "h1=\"second:2\"", "origin", 80, Alpn::H1);
    let found = a.lookup((b"origin", 80, Alpn::H1), ALL, NOW).unwrap();
    assert_eq!(found.host, b"second");
    assert_eq!(a.len(), 1);
    a.flush(b"origin", 80, Alpn::H1);
    // The origin's own host and port, by another version.
    parse(&mut a, "h2=\":80\"", "origin", 80, Alpn::H1);
    assert!(a.lookup((b"origin", 80, Alpn::H1), ALL, NOW).unwrap().same);
}

/// An IPv6 alternative is kept without its brackets and written with
/// them; a bad one is said and passed over.
#[test]
fn an_ipv6_alternative_is_written_in_brackets() {
    let mut a = AltSvc::default();
    let said = parse(&mut a, "h1=\"[ffff::1]:8181\"", "127.0.0.1", 80, Alpn::H1);
    assert_eq!(said, ["Added alt-svc: ffff::1:8181 over h1"]);
    let text = String::from_utf8(a.text().unwrap()).unwrap();
    assert!(
        text.ends_with("h1 127.0.0.1 80 h1 [ffff::1] 8181 \"20190125 22:34:21\" 0 0\n"),
        "{text}"
    );
    let said = parse(&mut a, "h1=\"[ffff::1:8181\"", "127.0.0.1", 80, Alpn::H1);
    assert_eq!(said, ["Bad alt-svc IPv6 hostname, ignoring."]);
    let said = parse(&mut a, "h1=\"", "127.0.0.1", 80, Alpn::H1);
    assert_eq!(said, ["Bad alt-svc hostname, ignoring."]);
}

/// `ma` is capped at two years, a huge one too; a file's date too long
/// is passed over, and one that cannot be read has expired.
#[test]
fn ages_and_dates_are_capped_and_checked() {
    let mut a = AltSvc::default();
    parse(
        &mut a,
        "h1=\"nowhere.foo:80\"; ma=315360000000000000000",
        "o",
        80,
        Alpn::H1,
    );
    // Not a number C reads: the default day.
    assert_eq!(a.entries[0].expires, NOW + DEFAULT_MAX_AGE);
    parse(
        &mut a,
        "h1=\"nowhere.foo:80\"; ma=315360000",
        "o",
        80,
        Alpn::H1,
    );
    // Two years of 365 days.
    assert_eq!(a.entries[0].expires, NOW + 63_072_000);
    let file = Temp::new(
        "dates",
        b"h1 a 1 h1 b 2 \"20290222 22:19:028\" 0 0\nh1 a 1 h1 b 2 \"nonsense\" 0 0\n\
          h1 a 1 h1 b 2 \"20290222 22:19:28\" 1 0",
    );
    let mut a = AltSvc::default();
    a.load(file.name(), NOW).unwrap();
    // Only the last, its newline added as C reads a last line.
    assert_eq!(a.len(), 1);
    assert!(a.entries[0].persist);
}

/// A line longer than C reads one fails the load; a directory adds
/// nothing and is still the file written back.
#[test]
fn a_long_line_fails_and_a_directory_adds_nothing() {
    let file = Temp::new("long", &[b'x'; MAX_LINE + 1]);
    let mut a = AltSvc::default();
    assert_eq!(a.load(file.name(), NOW), Err(LoadError::TooLarge));
    let dir = std::env::temp_dir();
    let dir = dir.as_os_str().as_encoded_bytes();
    a.load(dir, NOW).unwrap();
    assert_eq!(a.file(), Some(dir));
}

/// A file's line: a host as long as C reads one is kept, one longer is
/// not; the line must end after its priority; a source host of a dot
/// alone is none; brackets go from an IPv6 address, and then its dot
/// stays; a host of two brackets alone keeps them.
#[test]
fn a_file_s_lines_are_read_to_c_s_limits() {
    let long = "a".repeat(MAX_HOST_LEN);
    let longer = "a".repeat(MAX_HOST_LEN + 1);
    let lines = [
        format!("h1 {long} 1 h1 b 2 \"20991231 00:00:00\" 0 0\n"),
        format!("h1 {longer} 1 h1 b 2 \"20991231 00:00:00\" 0 0\n"),
        "h1 a 1 h1 b 2 \"20991231 00:00:00\" 0 0 trailing\n".to_string(),
        "h1 . 1 h1 b 2 \"20991231 00:00:00\" 0 0\n".to_string(),
        "h1 [a.] 1 h1 [c] 2 \"20991231 00:00:00\" 0 0\n".to_string(),
        "h1 [] 1 h1 d. 2 \"20991231 00:00:00\" 0 0\n".to_string(),
        "h1  e 1 h1 f 2 \"20991231 00:00:00\" 0 0\n".to_string(),
    ];
    let file = Temp::new("limits", lines.concat().as_bytes());
    let mut a = AltSvc::default();
    a.load(file.name(), NOW).unwrap();
    let hosts: Vec<(String, String)> = a
        .entries
        .iter()
        .map(|e| {
            let s = |h: &[u8]| String::from_utf8(h.to_vec()).unwrap();
            (s(&e.src.host), s(&e.dst.host))
        })
        .collect();
    assert_eq!(
        hosts,
        [
            (long.clone(), "b".into()),
            ("a.".into(), "c".into()),
            ("[]".into(), "d.".into()),
        ]
    );
    assert!(!a.is_empty());
    // An alternative of the longest hosts at both ends is written whole.
    let field = format!("h1=\"{long}:2\"");
    parse(&mut a, &field, &long, 1, Alpn::H1);
    let text = String::from_utf8(a.text().unwrap()).unwrap();
    assert!(
        text.contains(&format!("h1 {long} 1 h1 {long} 2 ")),
        "{}",
        text.len()
    );
}

/// A line as long as C's buffer holds, its newline counted, is read; one
/// longer fails the load, as does a last line without a newline that
/// one added would make too long.
#[test]
fn a_file_s_line_may_be_as_long_as_c_s_buffer() {
    let line = |len: usize, newline: bool| {
        let mut l = b"#".repeat(len - usize::from(newline));
        if newline {
            l.push(b'\n');
        }
        l
    };
    for (bytes, ok) in [
        (line(MAX_LINE, true), true),
        (line(MAX_LINE + 1, true), false),
        (line(MAX_LINE - 1, false), true),
        (line(MAX_LINE, false), false),
    ] {
        let file = Temp::new("buffer", &bytes);
        let mut a = AltSvc::default();
        let loaded = a.load(file.name(), NOW);
        assert_eq!(loaded.is_ok(), ok, "{} bytes", bytes.len());
    }
}

/// What a file says is written back byte for byte, as C writes it: a
/// host that is not UTF-8 is not re-encoded, and one long enough to fill
/// the line with two such hosts is saved whole rather than refused.
#[test]
fn a_file_s_hosts_are_saved_as_they_were_read() {
    let wide = vec![0xffu8; 1100];
    let mut lines = Vec::new();
    for (src, dst) in [(&wide[..], &wide[..]), (b"[::1]", b"alt")] {
        lines.extend_from_slice(b"h1 ");
        lines.extend_from_slice(src);
        lines.extend_from_slice(b" 80 h2 ");
        lines.extend_from_slice(dst);
        lines.extend_from_slice(b" 443 \"20991231 00:00:00\" 1 0\n");
    }
    let file = Temp::new("raw", &lines);
    let mut a = AltSvc::default();
    a.load(file.name(), NOW).unwrap();
    let mut want = b"# Your alt-svc cache. https://curl.se/docs/alt-svc.html\n\
        # This file was generated by libcurl! Edit at your own risk.\n"
        .to_vec();
    want.extend_from_slice(&lines);
    assert_eq!(a.text().unwrap(), want);
}

/// An alternative expiring this second is still taken (`expires < now`
/// is what goes); one before it goes.
#[test]
fn an_alternative_lasts_through_its_last_second() {
    let mut a = AltSvc::default();
    parse(&mut a, "h1=\"alt:1\"; ma=10", "o", 80, Alpn::H1);
    assert!(a.lookup((b"o", 80, Alpn::H1), ALL, NOW + 10).is_some());
    assert!(a.lookup((b"o", 80, Alpn::H1), ALL, NOW + 11).is_none());
}

/// An origin whose host is a dot alone keeps nothing and says nothing,
/// and the reading goes on; C fails the transfer for memory there.
#[test]
fn an_origin_named_by_a_dot_alone_keeps_nothing() {
    let mut a = AltSvc::default();
    let said = parse(&mut a, "h1=\"alt:1\", h2=\"alt:2\"", ".", 80, Alpn::H1);
    assert!(a.is_empty());
    assert!(said.is_empty(), "{said:?}");
}

/// Blanks of any number, spaces or tabs, may come before a parameter's
/// `;`; a quoted parameter that does not end, or ends in a backslash,
/// ends the parameters, and an escaped quote does not end it.
#[test]
fn parameters_are_read_as_c_reads_them() {
    let mut a = AltSvc::default();
    parse(&mut a, "h1=\"alt:1\"  ; ma=5", "o", 80, Alpn::H1);
    assert_eq!(a.entries[0].expires, NOW + 5);
    for value in [
        "h1=\"alt:1\"; x=\"open; ma=5",
        "h1=\"alt:1\"; x=\"open\\",
        "h1=\"alt:1\"; x=\"a\\\"; ma=5",
    ] {
        let mut a = AltSvc::default();
        parse(&mut a, value, "o", 80, Alpn::H1);
        assert_eq!(a.entries[0].expires, NOW + DEFAULT_MAX_AGE, "{value}");
    }
    // Escaped, the quote is inside; the value goes on to the next one.
    let mut a = AltSvc::default();
    parse(
        &mut a,
        "h1=\"alt:1\"; x=\"a\\\"b\"; ma=5",
        "o",
        80,
        Alpn::H1,
    );
    assert_eq!(a.entries[0].expires, NOW + 5);
}

/// A quoted word is as long as `max` allows, an escaped byte counting
/// with its backslash: the date of a file's line, at most 17 bytes.
#[test]
fn a_quoted_word_is_at_most_its_limit() {
    let mut c = Cursor::new(b"\"12345\" rest");
    assert_eq!(c.quoted(5), Some(&b"12345"[..]));
    assert_eq!(c.rest(), b" rest");
    assert_eq!(Cursor::new(b"\"123456\"").quoted(5), None);
    // `\"` counts as two.
    assert_eq!(Cursor::new(b"\"123\\\"\"").quoted(5), Some(&b"123\\\""[..]));
    assert_eq!(Cursor::new(b"\"1234\\\"\"").quoted(5), None);
    assert_eq!(Cursor::new(b"\"1234\\").quoted(9), None);
    assert_eq!(Cursor::new(b"\"12").quoted(9), None);
}
