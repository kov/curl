"""
Shared helpers for the inventory generators.

Every generator reads the C tree, builds a list of records, checks it
against an independent signal (a positive control), and writes two files:

  inventory/<name>.json  -- the data, sorted and stable, for tools to consume
  inventory/<name>.md    -- a generated human summary of the same data

Neither file is edited by hand. Fix the generator instead.
"""

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
INVENTORY = ROOT / "inventory"


# The C reference tree: upstream's top-level entries, but for its READMEs,
# which the rewrite's replace (upstream's are kept as README.upstream*).
# Everything else belongs to the rewrite, so a file it adds never reads as
# a change to the C tree. An entry upstream adds at the top is added here
# with the merge that brings it (UPSTREAM.md).
C_TREE = [".clang-tidy.yml", ".dir-locals.el", ".editorconfig", ".git-blame-ignore-revs",
          ".gitattributes", ".github", ".gitignore", ".mailmap", "CHANGES.md", "CMake",
          "CMakeLists.txt", "COPYING", "Dockerfile", "GIT-INFO.md", "LICENSES", "Makefile.am",
          "RELEASE-NOTES", "REUSE.toml", "SECURITY.md", "acinclude.m4", "appveyor.sh",
          "appveyor.yml", "configure.ac", "curl-config.in", "docs", "include", "lib",
          "libcurl.pc.in", "m4", "projects", "scripts", "src", "tests"]


def rewrite_paths(*also_c):
    """The git pathspec of everything outside the C tree and `also_c`."""
    return [".", *(f":(exclude){p}" for p in [*C_TREE, *also_c])]


def c_commit():
    """
    Return the last commit that changed the C tree.

    Suffixed with `-dirty` when tracked C tree files have local changes.
    """
    def git(*args):
        return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                              capture_output=True, text=True).stdout.strip()
    sha = git("log", "-1", "--format=%H", "--", *C_TREE)
    dirty = git("status", "--porcelain", "--untracked-files=no", "--", *C_TREE)
    return sha + ("-dirty" if dirty else "")


def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8", errors="strict")


def frontmatter(text):
    """
    Parse the YAML-ish frontmatter used by docs/libcurl/opts and
    docs/cmdline-opts: `Key: value` scalars and `Key:` followed by
    indented `- item` lists. Returns (dict, body)."""
    if not text.startswith("---\n"):
        raise ValueError("no frontmatter")
    end = text.index("\n---\n", 4)
    head, body = text[4:end], text[end + 5:]
    meta, key = {}, None
    for line in head.splitlines():
        m = re.match(r"^\s+- (.*)$", line)
        if m:
            if key is None or not isinstance(meta[key], list):
                raise ValueError(f"list item without list key: {line!r}")
            meta[key].append(m.group(1).strip())
            continue
        m = re.match(r"^([A-Za-z][A-Za-z0-9-]*):\s*(.*)$", line)
        if not m:
            raise ValueError(f"unparsed frontmatter line: {line!r}")
        key, val = m.group(1), m.group(2).strip()
        if key in meta:
            raise ValueError(f"duplicate frontmatter key {key!r}")
        meta[key] = val or []
    return meta, body


def check(cond, msg):
    """
    Stop the generator when a self-check fails.

    Stale or wrong data must never be written.
    """
    if not cond:
        sys.exit(f"{pathlib.Path(sys.argv[0]).name}: check failed: {msg}")


def write(name, data, summary_md, sources, generated_by=None):
    """
    Write inventory/<name>.json and inventory/<name>.md.

    `sources` lists the C tree paths the data was derived from."""
    doc = {
        "generated-by": generated_by or f"inventory/gen/{name}.py",
        "c-commit": c_commit(),
        "sources": sorted(sources),
        "data": data,
    }
    (INVENTORY / f"{name}.json").write_text(
        json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n")
    header = (
        f"<!-- Generated by {doc['generated-by']} from C commit "
        f"{doc['c-commit'][:12]}. Do not edit; regenerate. -->\n\n")
    (INVENTORY / f"{name}.md").write_text(
        docs_lint_safe(header + summary_md.rstrip() + "\n"))


def docs_lint_safe(md):
    """
    Keep generated Markdown clear of tests/test1275.pl.

    That C test flags a lowercase word after a period in every tracked .md
    file, and summaries quote C text ("prelim. reply") that trips it. A
    `&#32;` renders as the same space but is not one to the check.
    """
    md = re.sub(r"\. +(?=[a-z])", ".&#32;", md)
    # A line starting lowercase after a line ending in a period.
    return re.sub(r"\.\n( *)(?=[a-z])", ".\n\\1&#32;", md)


def md_table(headers, rows):
    def cell(v):
        if isinstance(v, (list, tuple)):
            v = ", ".join(str(x) for x in v)
        return str(v if v is not None else "").replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return "\n".join(out) + "\n"
