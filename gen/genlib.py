"""
Shared by the generators of Rust code in gen/.

Each generated file starts with a header naming the generator, the
files it was generated from and a hash of them. The `generated_is_fresh`
test in curl-sys-abi recomputes the hash of every such file in crates/,
so a stale file fails `cargo test` without Python.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ABI = ROOT / "inventory" / "abi.json"


def check(cond, msg):
    if not cond:
        sys.exit(f"{pathlib.Path(sys.argv[0]).name}: {msg}")


def fnv1a(data):
    """FNV-1a, 64 bits: enough to detect a stale file, not a security hash."""
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def input_bytes(path):
    data = path.read_bytes()
    if path.suffix == ".json":
        # The inventory's C commit stamp moves with every C commit, even
        # when nothing it describes changed.
        data = b"".join(line for line in data.splitlines(keepends=True)
                        if not line.startswith(b' "c-commit": '))
    return data


def header(generator, inputs):
    """Return the header of a file `generator` writes from `inputs`."""
    names = [p.relative_to(ROOT).as_posix() for p in inputs]
    digest = fnv1a(b"".join(input_bytes(p) for p in inputs))
    return (f"// Generated by {generator.relative_to(ROOT).as_posix()}. "
            "Do not edit; run gen/all.py.\n"
            f"// inputs: {' '.join(names)}\n"
            f"// inputs-hash: {digest:016x}\n\n")


def write(path, text):
    """Write `path`, or with `--check` fail if it would change."""
    if "--check" in sys.argv[1:]:
        check(path.exists() and path.read_text() == text,
              f"{path.relative_to(ROOT)} is stale; run gen/all.py")
        return
    path.write_text(text)
