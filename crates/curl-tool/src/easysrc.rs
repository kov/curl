    /// Only `Setopt` changes a transfer's options: one changed elsewhere
    /// would have no line in the program.
    #[test]
    fn only_setopt_changes_options() {
        fn sources(dir: &std::path::Path, found: &mut Vec<std::path::PathBuf>) {
            for entry in std::fs::read_dir(dir).unwrap() {
                let path = entry.unwrap().path();
                if path.is_dir() {
                    sources(&path, found);
                } else if path.extension().is_some_and(|e| e == "rs") {
                    found.push(path);
                }
            }
        }
        let mut found = Vec::new();
        sources(
            &std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src"),
            &mut found,
        );
        assert!(found.len() > 20, "the tool's sources are found");
        let mut reached = Vec::new();
        for path in found {
            let text = std::fs::read_to_string(&path).unwrap();
            if text.contains(".options_mut(") {
                reached.push(path.file_name().unwrap().to_string_lossy().into_owned());
            }
        }
        assert_eq!(reached, ["easysrc.rs"]);
    }

    /// The lines `Setopt` writes for `set`, each value as C's wrappers
    /// write it.
    fn lines(set: impl FnOnce(&mut Setopt<'_>)) -> Vec<String> {
        let mut easy = Easy::new();
        let mut source = Source::default();
        set(&mut Setopt::new(&mut easy, Some(&mut source)));
        source
            .code
            .iter()
            .map(|l| String::from_utf8(l.clone()).unwrap())
            .collect()
    }

