//! The cookie jar (`lib/cookie.c`): the cookies servers set, and those read
//! from files and given by the application, each in the Netscape file
//! format or as a `Set-Cookie:` line, sent back to the hosts and paths
//! they match.
//!
//! The jar keeps C's 63 buckets, hashed on the last two labels of each
//! domain, and the order within them: which cookies a request considers
//! first, and the order the jar is listed in, are what they make them.

use std::cmp::Ordering;

use curl_alloc::{OutOfMemory, TryArc, TryVec as _};

use crate::url::is_ip_address;

#[cfg(test)]
mod tests;

/// How many buckets the jar hashes cookies into (`COOKIE_HASH_SIZE`).
const BUCKETS: usize = 63;

/// The longest `Set-Cookie:` value read; longer lines are passed over
/// (`MAX_COOKIE_LINE`).
const MAX_LINE: usize = 5000;

/// The most a cookie's name and value may hold together (`MAX_NAME`).
const MAX_NAME: usize = 4096;

/// The most `Set-Cookie:` lines one request stores
/// (`MAX_SET_COOKIE_AMOUNT`).
pub(crate) const MAX_SET_PER_REQUEST: u8 = 50;

/// The most cookies one request sends (`MAX_COOKIE_SEND_AMOUNT`).
const MAX_SEND: usize = 150;

/// No cookie lasts more than 400 days from when it is set
/// (`COOKIES_MAXAGE`).
const MAX_AGE: i64 = 400 * 24 * 3600;

/// The longest `Expires` read as a date (`MAX_DATE_LENGTH`).
const MAX_DATE_LEN: usize = 80;

/// What C's printf writes for a string that is not there.
const NIL: &[u8] = b"(nil)";

/// The head of a file the jar is written to.
const FILE_HEAD: &[u8] = b"# Netscape HTTP Cookie File\n\
    # https://curl.se/docs/http-cookies.html\n\
    # This file was generated by libcurl! Edit at your own risk.\n\n";

/// Which domains are public suffixes, on which no cookie may be set for
/// all the hosts below (libpsl).
pub trait PublicSuffixes: Send + Sync {
    /// Whether `domain`, in lower case, is a public suffix
    /// (`psl_is_public_suffix`).
    fn is_public_suffix(&self, domain: &[u8]) -> bool;

    /// Whether `host` may set a cookie for `domain`, both in lower case
    /// (`psl_is_cookie_domain_acceptable`).
    fn accepts(&self, host: &[u8], domain: &[u8]) -> bool;

    /// Whether the list could be had: without it, every domain is
    /// refused (`Curl_psl_use` failing).
    fn available(&self) -> bool {
        true
    }
}

/// A list of public suffixes, shared by the handles given it.
#[derive(Clone)]
pub struct Suffixes(TryArc<Box<dyn PublicSuffixes>>);

impl Suffixes {
    pub fn new(list: Box<dyn PublicSuffixes>) -> Result<Suffixes, OutOfMemory> {
        Ok(Suffixes(TryArc::try_new(list)?))
    }

    pub(crate) fn list(&self) -> &dyn PublicSuffixes {
        &**self.0
    }
}

impl std::fmt::Debug for Suffixes {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Suffixes")
    }
}

/// One cookie.
#[derive(Debug)]
pub(crate) struct Cookie {
    name: Vec<u8>,
    value: Vec<u8>,
    /// The paths it is sent for, without a trailing slash; none where it
    /// was read from a `Set-Cookie:` line in a file that names none.
    path: Option<Vec<u8>>,
    /// The host it was set for, or the domain it names; none as with the
    /// path.
    domain: Option<Vec<u8>>,
    /// When it expires, in seconds since 1970; zero for a cookie that
    /// lasts the session.
    expires: i64,
    /// When it was stored, counted per jar; unique, and kept by a cookie
    /// that replaces it.
    created: u32,
    /// It goes to the hosts below its domain too.
    tailmatch: bool,
    /// It goes only over a secure connection.
    secure: bool,
    /// It was set by a server, not read from a file.
    live: bool,
    http_only: bool,
    prefix: Prefix,
}

/// What a cookie's name promises (draft-ietf-httpbis-rfc6265bis-02).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
enum Prefix {
    #[default]
    None,
    /// `__Secure-`: it must be set secure.
    Secure,
    /// `__Host-`: secure, for `/`, and for its host alone.
    Host,
}

impl Prefix {
    fn of(name: &[u8]) -> Prefix {
        if name.starts_with(b"__Secure-") {
            Prefix::Secure
        } else if name.starts_with(b"__Host-") {
            Prefix::Host
        } else {
            Prefix::None
        }
    }
}

impl Cookie {
    pub(crate) fn name(&self) -> &[u8] {
        &self.name
    }

    pub(crate) fn value(&self) -> &[u8] {
        &self.value
    }

    /// The cookie as a line of a Netscape file, without its end
    /// (`get_netscape_format`).
    pub(crate) fn netscape(&self, out: &mut Vec<u8>) -> Result<(), OutOfMemory> {
        if self.http_only {
            out.try_extend_from_slice(b"#HttpOnly_")?;
        }
        // A cookie for the hosts below its domain is written as Mozilla
        // writes it, after a dot.
        if self.tailmatch
            && self
                .domain
                .as_ref()
                .is_some_and(|d| d.first() != Some(&b'.'))
        {
            out.try_extend_from_slice(b".")?;
        }
        let mut digits = [0u8; 20];
        for (i, field) in [
            self.domain.as_deref().unwrap_or(b"unknown"),
            truth(self.tailmatch),
            self.path.as_deref().unwrap_or(b"/"),
            truth(self.secure),
            signed(self.expires, &mut digits),
            &self.name,
            &self.value,
        ]
        .into_iter()
        .enumerate()
        {
            if i > 0 {
                out.try_extend_from_slice(b"\t")?;
            }
            out.try_extend_from_slice(field)?;
        }
        Ok(())
    }
}

fn truth(b: bool) -> &'static [u8] {
    if b { b"TRUE" } else { b"FALSE" }
}

/// `n` in decimal, a minus before it if it is negative.
fn signed(n: i64, buf: &mut [u8; 20]) -> &[u8] {
    let mut at = buf.len();
    let mut m = n.unsigned_abs();
    loop {
        at -= 1;
        buf[at] = b'0' + (m % 10) as u8;
        m /= 10;
        if m == 0 {
            break;
        }
    }
    if n < 0 {
        at -= 1;
        buf[at] = b'-';
    }
    &buf[at..]
}

/// Where a line given to the jar comes from, which decides how far it is
/// trusted.
#[derive(Clone, Copy, Debug)]
pub(crate) enum Source<'a> {
    /// A `Set-Cookie:` field's value from a server: the host it came from
    /// (a custom `Host:` header's name where one was sent) and the path
    /// of the URL asked for, which give a cookie its default domain and
    /// path. `secure`: the connection was, or the host is this one.
    Server {
        host: &'a [u8],
        path: &'a [u8],
        secure: bool,
    },
    /// A line of a file read into the jar; its public suffixes are
    /// checked unless `trusted`, as on a reload the application asks for.
    File { trusted: bool },
    /// A line the application gives (`CURLOPT_COOKIELIST`).
    Application,
}

impl Source<'_> {
    fn secure(&self) -> bool {
        match self {
            Source::Server { secure, .. } => *secure,
            Source::File { .. } | Source::Application => true,
        }
    }

    fn checks_suffixes(&self) -> bool {
        matches!(
            self,
            Source::Server { .. } | Source::File { trusted: false }
        )
    }

    /// Whether storing a cookie first sweeps out those expired: a file
    /// is swept once, when it has been read.
    fn sweeps(&self) -> bool {
        !matches!(self, Source::File { .. })
    }
}

/// What the jar says of a line it was given (`infof`), if anything.
#[derive(Debug)]
pub(crate) enum Said<'a> {
    /// The first pair had no name, or no `=`.
    Invalid,
    Oversized {
        name: usize,
        value: usize,
    },
    NameOctets,
    ValueOctets,
    /// `secure` from a server the connection to which was not.
    NotSecure,
    /// A domain the host is not in.
    BadDomain(&'a [u8]),
    /// A domain that is a public suffix, set by `host`: none from a file;
    /// `problem`: no list could be had, so every domain is refused.
    PublicSuffix {
        cookie: Cookie,
        host: Option<&'a [u8]>,
        problem: bool,
    },
    /// It would overlay a secure cookie, set over a connection that was
    /// not.
    Overlay(Cookie),
    /// Stored, by a server.
    Stored {
        replaced: bool,
        cookie: &'a Cookie,
    },
}

impl Said<'_> {
    /// The lines C traces, each in parts.
    pub(crate) fn lines(&self, mut f: impl FnMut(&[&[u8]])) {
        let mut a = [0u8; 20];
        let mut b = [0u8; 20];
        match self {
            Said::Invalid => f(&[b"invalid cookie, dropped"]),
            Said::Oversized { name, value } => f(&[
                b"oversized cookie dropped, name/val ",
                signed(*name as i64, &mut a),
                b" + ",
                signed(*value as i64, &mut b),
                b" bytes",
            ]),
            Said::NameOctets => f(&[b"invalid octets in name, cookie dropped"]),
            Said::ValueOctets => f(&[b"invalid octets in value, cookie dropped"]),
            Said::NotSecure => f(&[b"skipped cookie because not 'secure'"]),
            Said::BadDomain(domain) => f(&[b"skipped cookie with bad tailmatch domain: ", domain]),
            Said::PublicSuffix {
                cookie,
                host,
                problem,
            } => {
                if *problem {
                    f(&[b"libpsl problem, rejecting cookie for safety"]);
                }
                f(&[
                    b"cookie '",
                    &cookie.name,
                    b"' dropped, domain '",
                    host.unwrap_or(b"[file]"),
                    b"' must not set cookies for '",
                    cookie.domain.as_deref().unwrap_or(NIL),
                    b"'",
                ]);
            }
            Said::Overlay(cookie) => f(&[
                b"cookie '",
                &cookie.name,
                b"' for domain '",
                cookie.domain.as_deref().unwrap_or(NIL),
                b"' dropped, would overlay an existing cookie",
            ]),
            Said::Stored { replaced, cookie } => f(&[
                if *replaced { b"Replaced" } else { b"Added" },
                b" cookie ",
                &cookie.name,
                b"=\"",
                &cookie.value,
                b"\" for domain ",
                cookie.domain.as_deref().unwrap_or(NIL),
                b", path ",
                cookie.path.as_deref().unwrap_or(NIL),
                b", expire ",
                signed(cookie.expires, &mut a),
            ]),
        }
    }
}

/// The cookies a request sends, in the order it sends them.
pub(crate) struct Matching<'j> {
    pub(crate) cookies: Vec<&'j Cookie>,
    /// More matched than a request sends (`MAX_COOKIE_SEND_AMOUNT`).
    pub(crate) capped: bool,
}

impl Matching<'_> {
    /// What C says when the cookies are capped.
    pub(crate) fn capped_line<R>(&self, f: impl FnOnce(&[&[u8]]) -> R) -> R {
        let mut n = [0u8; 20];
        f(&[
            b"Included max number of cookies (",
            signed(MAX_SEND as i64, &mut n),
            b") in request!",
        ])
    }
}

/// The cookies known (`struct CookieInfo`).
#[derive(Debug)]
pub(crate) struct Jar {
    /// `BUCKETS` of them once the first cookie is stored, none before.
    buckets: Vec<Vec<Cookie>>,
    /// The earliest any cookie expires, or `i64::MAX` if that is not
    /// known: no sweep before then finds anything.
    next_expiry: i64,
    count: usize,
    last_created: u32,
    /// A transfer has started: cookies stored from now on are a server's
    /// (`running`).
    running: bool,
    /// Session cookies in the files read are passed over (`newsession`).
    new_session: bool,
}

impl Default for Jar {
    fn default() -> Self {
        Jar {
            buckets: Vec::new(),
            next_expiry: i64::MAX,
            count: 0,
            last_created: 0,
            running: false,
            new_session: false,
        }
    }
}

impl Jar {
    /// How many cookies it holds.
    pub(crate) fn len(&self) -> usize {
        self.count
    }

    /// Whether a transfer has started since the files were last read: a
    /// jar that has not is not saved, its files perhaps not all read.
    pub(crate) fn running(&self) -> bool {
        self.running
    }

    /// From now on, cookies are stored as a server's.
    pub(crate) fn start(&mut self) {
        self.running = true;
    }

    /// Read a file's `text` into the jar (`cookie_load`), its lines each
    /// a cookie in the Netscape format or a `Set-Cookie:` line; those
    /// that are neither are passed over. `new_session` passes over the
    /// cookies that last the session; `trusted` does not check public
    /// suffixes, as on a reload the application asks for. The jar is
    /// swept after, and then started.
    pub(crate) fn load(
        &mut self,
        text: &[u8],
        new_session: bool,
        trusted: bool,
        suffixes: Option<&dyn PublicSuffixes>,
        now: i64,
    ) -> Result<(), OutOfMemory> {
        self.new_session = new_session;
        self.running = false;
        // A file's `Set-Cookie:` lines count against one request's.
        let mut set = 0;
        for line in text.split_inclusive(|&b| b == b'\n') {
            let line = match strip_prefix_ignore_case(line, b"Set-Cookie:") {
                Some(rest) => Line::Header(trim_start(rest)),
                None => Line::Netscape(line),
            };
            self.add(line, Source::File { trusted }, suffixes, now, &mut set)?;
        }
        self.sweep(now);
        self.running = true;
        Ok(())
    }

    /// Store a line the application gives (`CURLOPT_COOKIELIST`): a
    /// `Set-Cookie:` line or one in the Netscape format.
    pub(crate) fn add_line(
        &mut self,
        line: &[u8],
        suffixes: Option<&dyn PublicSuffixes>,
        now: i64,
        set: &mut u8,
    ) -> Result<(), OutOfMemory> {
        let line = match strip_prefix_ignore_case(line, b"Set-Cookie:") {
            Some(rest) => Line::Header(rest),
            None => Line::Netscape(line),
        };
        self.add(line, Source::Application, suffixes, now, set)?;
        Ok(())
    }

    /// Store the cookie a server's `Set-Cookie:` field sets, `value`
    /// being all after the colon. `set` counts the fields this request
    /// has stored.
    pub(crate) fn set_by<'a>(
        &'a mut self,
        value: &'a [u8],
        source: Source<'a>,
        suffixes: Option<&dyn PublicSuffixes>,
        now: i64,
        set: &mut u8,
    ) -> Result<Option<Said<'a>>, OutOfMemory> {
        self.add(Line::Header(value), source, suffixes, now, set)
    }

    /// Store the cookie `line` gives, if it is one the jar takes
    /// (`Curl_cookie_add`).
    fn add<'a>(
        &'a mut self,
        line: Line<'a>,
        source: Source<'a>,
        suffixes: Option<&dyn PublicSuffixes>,
        now: i64,
        set: &mut u8,
    ) -> Result<Option<Said<'a>>, OutOfMemory> {
        if *set >= MAX_SET_PER_REQUEST {
            return Ok(None);
        }
        let header = matches!(line, Line::Header(_));
        let parsed = match line {
            Line::Header(value) => header_cookie(value, source, suffixes, now)?,
            Line::Netscape(line) => self.netscape_cookie(line, source.secure())?,
        };
        let mut co = match parsed {
            Parsed::Cookie(co) => co,
            Parsed::Dropped(said) => return Ok(said),
        };
        if co.prefix == Prefix::Secure && !co.secure {
            return Ok(None);
        }
        let host = match source {
            Source::Server { host, .. } => Some(host),
            Source::File { .. } | Source::Application => None,
        };
        if source.checks_suffixes()
            && let Some(suffixes) = suffixes
            && let Some(problem) = on_public_suffix(&mut co, host, suffixes)
        {
            return Ok(Some(Said::PublicSuffix {
                cookie: co,
                host,
                problem,
            }));
        }
        if co.prefix == Prefix::Host
            && !(co.secure && co.path.as_deref() == Some(b"/") && !co.tailmatch)
        {
            return Ok(None);
        }
        if !self.running && self.new_session && co.expires == 0 {
            return Ok(None);
        }
        co.live = self.running;
        self.last_created = self.last_created.wrapping_add(1);
        co.created = self.last_created;
        if source.sweeps() {
            self.sweep(now);
        }
        if self.buckets.is_empty() {
            self.buckets.try_reserve_exact(BUCKETS)?;
            self.buckets.resize_with(BUCKETS, Vec::new);
        }
        let bucket = bucket(co.domain.as_deref());
        let replaced = match self.replaced(&co, bucket, source.secure()) {
            Replace::Refused { overlay: true } => return Ok(Some(Said::Overlay(co))),
            Replace::Refused { overlay: false } => return Ok(None),
            Replace::At(at) => {
                // The new cookie keeps the creation time of the one it
                // replaces, and goes to the end.
                let old = self.buckets[bucket].remove(at);
                co.created = old.created;
                true
            }
            Replace::Nothing => false,
        };
        if co.expires != 0 && co.expires < self.next_expiry {
            self.next_expiry = co.expires;
        }
        self.buckets[bucket].try_push(co)?;
        if !replaced {
            self.count += 1;
        }
        if header {
            *set += 1;
        }
        let cookie = self.buckets[bucket].last().expect("just pushed");
        Ok(self.running.then_some(Said::Stored { replaced, cookie }))
    }

    /// Whether `co` replaces a cookie in `bucket`, and which
    /// (`replace_existing`); `secure`: it came over a secure connection.
    fn replaced(&self, co: &Cookie, bucket: usize, secure: bool) -> Replace {
        let mut at = None;
        for (i, old) in self.buckets[bucket].iter().enumerate() {
            if old.name != co.name {
                continue;
            }
            let overlapping = match (&old.domain, &co.domain) {
                (Some(a), Some(b)) => tailmatch(a, b) || tailmatch(b, a),
                (None, None) => true,
                _ => false,
            };
            // A cookie from a connection that is not secure may not
            // overlay a secure one: for an existing cookie with path
            // `/login/en`, no new one whose path starts `/login`.
            if overlapping
                && old.secure
                && !co.secure
                && !secure
                && let (Some(old_path), Some(path)) = (&old.path, &co.path)
            {
                let first = old_path
                    .iter()
                    .skip(1)
                    .position(|&b| b == b'/')
                    .map_or(old_path.len(), |p| p + 1);
                if path.starts_with(&old_path[..first]) {
                    return Replace::Refused { overlay: true };
                }
            }
            if at.is_some() {
                continue;
            }
            let same_domain = match (&old.domain, &co.domain) {
                (Some(a), Some(b)) => a.eq_ignore_ascii_case(b) && old.tailmatch == co.tailmatch,
                (None, None) => true,
                _ => false,
            };
            if same_domain && old.path == co.path {
                // A cookie a server set is kept over one read from a file.
                if !co.live && old.live {
                    return Replace::Refused { overlay: false };
                }
                at = Some(i);
            }
        }
        at.map_or(Replace::Nothing, Replace::At)
    }

    /// Remove the cookies expired by `now` (`remove_expired`).
    pub(crate) fn sweep(&mut self, now: i64) {
        // Nothing has expired before the earliest any cookie does.
        if now < self.next_expiry && self.next_expiry != i64::MAX {
            return;
        }
        self.next_expiry = i64::MAX;
        for bucket in &mut self.buckets {
            let before = bucket.len();
            bucket.retain(|co| co.expires == 0 || co.expires >= now);
            self.count -= before - bucket.len();
            for co in bucket.iter() {
                if co.expires != 0 && co.expires < self.next_expiry {
                    self.next_expiry = co.expires;
                }
            }
        }
    }

    /// The cookies a request to `host` for `path` sends, longest path
    /// first (`Curl_cookie_getlist`); `secure`: over a secure connection,
    /// or to this host. The jar is to be swept first.
    pub(crate) fn matching(
        &self,
        host: &[u8],
        path: &[u8],
        secure: bool,
    ) -> Result<Matching<'_>, OutOfMemory> {
        let is_ip = is_ip_address(host);
        let mut cookies = Vec::new();
        let mut capped = false;
        for co in self.buckets.get(bucket(Some(host))).into_iter().flatten() {
            if co.secure && !secure {
                continue;
            }
            let domain_matches = match &co.domain {
                None => true,
                Some(d) if co.tailmatch && !is_ip => tailmatch(d, host),
                Some(d) => host.eq_ignore_ascii_case(d),
            };
            if !domain_matches || !co.path.as_deref().is_none_or(|p| path_matches(p, path)) {
                continue;
            }
            cookies.try_push(co)?;
            if cookies.len() >= MAX_SEND {
                capped = true;
                break;
            }
        }
        // A name set for more than one path goes with its longest first.
        cookies.sort_unstable_by(|a, b| send_order(a, b));
        Ok(Matching { cookies, capped })
    }

    /// The cookies that have a domain, in the order of the buckets, each
    /// in the Netscape format (`CURLINFO_COOKIELIST`). The jar is to be
    /// swept first.
    pub(crate) fn listed(&self) -> impl Iterator<Item = &Cookie> {
        self.buckets
            .iter()
            .flatten()
            .filter(|co| co.domain.is_some())
    }

    /// The jar as a Netscape file (`cookie_output`), newest first: the
    /// cookies that have a domain. The jar is swept first.
    pub(crate) fn file(&mut self, now: i64, out: &mut Vec<u8>) -> Result<(), OutOfMemory> {
        self.sweep(now);
        out.try_extend_from_slice(FILE_HEAD)?;
        let mut cookies = Vec::new();
        for co in self.listed() {
            cookies.try_push(co)?;
        }
        cookies.sort_unstable_by_key(|co| std::cmp::Reverse(co.created));
        for co in cookies {
            co.netscape(out)?;
            out.try_extend_from_slice(b"\n")?;
        }
        Ok(())
    }

    /// Forget every cookie (`Curl_cookie_clearall`).
    pub(crate) fn clear(&mut self) {
        for bucket in &mut self.buckets {
            *bucket = Vec::new();
        }
        self.count = 0;
    }

    /// Forget the cookies that last the session (`Curl_cookie_clearsess`).
    pub(crate) fn clear_session(&mut self) {
        for bucket in &mut self.buckets {
            let before = bucket.len();
            bucket.retain(|co| co.expires != 0);
            self.count -= before - bucket.len();
        }
    }

    /// A Netscape line read into a cookie (`parse_netscape`); `secure`:
    /// a secure cookie may be stored. Lines that are not cookies are
    /// passed over without a word.
    fn netscape_cookie(&self, line: &[u8], secure: bool) -> Result<Parsed<'static>, OutOfMemory> {
        let mut line = until_zero(line);
        let mut co = Cookie::empty();
        // Firefox writes cookies scripts may not read after `#HttpOnly_`.
        if let Some(rest) = line.strip_prefix(b"#HttpOnly_") {
            line = rest;
            co.http_only = true;
        }
        if line.first() == Some(&b'#') {
            return Ok(Parsed::Dropped(None));
        }
        let mut fields = 0;
        let mut next = Some(line);
        while let Some(rest) = next {
            let len = rest
                .iter()
                .position(|b| matches!(b, b'\t' | b'\r' | b'\n'))
                .unwrap_or(rest.len());
            let field = &rest[..len];
            next = (rest.get(len) == Some(&b'\t')).then(|| &rest[len + 1..]);
            if fields == 2 {
                // The file may leave the path out: a field that reads as
                // the next is taken for it.
                if !(is_prefix_of(field, b"TRUE") || is_prefix_of(field, b"FALSE")) {
                    co.path = Some(sanitized_path(field)?);
                    fields += 1;
                    continue;
                }
                co.path = Some(copy(b"/")?);
                fields += 1;
            }
            match fields {
                0 => co.domain = Some(copy(field.strip_prefix(b".").unwrap_or(field))?),
                1 => co.tailmatch = is_prefix_of_ignore_case(field, b"TRUE"),
                3 => {
                    co.secure = false;
                    if is_prefix_of_ignore_case(field, b"TRUE") {
                        if !secure && !self.running {
                            return Ok(Parsed::Dropped(None));
                        }
                        co.secure = true;
                    }
                }
                4 => match number(field) {
                    Number::Ok(n) => co.expires = n,
                    Number::None | Number::Overflow => return Ok(Parsed::Dropped(None)),
                },
                5 => {
                    co.name = copy(field)?;
                    co.prefix = Prefix::of(field);
                }
                6 => co.value = copy(field)?,
                _ => {}
            }
            fields += 1;
        }
        // A cookie whose value is left out is empty.
        if fields == 6 {
            fields += 1;
        }
        if fields != 7 || invalid_octets(&co.name) || invalid_octets(&co.value) {
            return Ok(Parsed::Dropped(None));
        }
        Ok(Parsed::Cookie(co))
    }
}

/// A line given to the jar.
#[derive(Clone, Copy)]
enum Line<'a> {
    /// What follows `Set-Cookie:`.
    Header(&'a [u8]),
    Netscape(&'a [u8]),
}

enum Parsed<'a> {
    Cookie(Cookie),
    Dropped(Option<Said<'a>>),
}

enum Replace {
    Nothing,
    At(usize),
    /// The new cookie is not stored; `overlay`: because it would overlay a
    /// secure one, which C says.
    Refused {
        overlay: bool,
    },
}

impl Cookie {
    fn empty() -> Cookie {
        Cookie {
            name: Vec::new(),
            value: Vec::new(),
            path: None,
            domain: None,
            expires: 0,
            created: 0,
            tailmatch: false,
            secure: false,
            live: false,
            http_only: false,
            prefix: Prefix::None,
        }
    }
}

/// A `Set-Cookie:` value read into a cookie (`parse_cookie_header`).
fn header_cookie<'a>(
    value: &'a [u8],
    source: Source<'a>,
    suffixes: Option<&dyn PublicSuffixes>,
    now: i64,
) -> Result<Parsed<'a>, OutOfMemory> {
    let value = until_zero(value);
    if value.len() > MAX_LINE {
        return Ok(Parsed::Dropped(None));
    }
    let (mut host, default_path) = match source {
        Source::Server { host, path, .. } => (Some(host), Some(path)),
        Source::File { .. } | Source::Application => (None, None),
    };
    let mut co = Cookie::empty();
    let mut name_value: Option<(&[u8], &[u8])> = None;
    let mut path: &[u8] = b"";
    let mut domain: &[u8] = b"";
    let mut rest = value;
    loop {
        let end = rest
            .iter()
            .position(|b| matches!(b, b';' | b'\r' | b'\n' | b'='))
            .unwrap_or(rest.len());
        let name = trim(&rest[..end]);
        rest = &rest[end..];
        if invalid_octets(name) {
            return Ok(Parsed::Dropped(Some(Said::NameOctets)));
        }
        let sep = rest.first() == Some(&b'=');
        let mut val: &[u8] = b"";
        if sep {
            rest = &rest[1..];
            let end = rest
                .iter()
                .position(|b| matches!(b, b';' | b'\r' | b'\n'))
                .unwrap_or(rest.len());
            val = trim(&rest[..end]);
            rest = &rest[end..];
            if invalid_octets(val) {
                return Ok(Parsed::Dropped(Some(Said::ValueOctets)));
            }
        }
        if name_value.is_none() {
            // The first pair is the cookie's name and value.
            if !sep || name.is_empty() {
                return Ok(Parsed::Dropped(Some(Said::Invalid)));
            }
            if name.len() + val.len() > MAX_NAME {
                return Ok(Parsed::Dropped(Some(Said::Oversized {
                    name: name.len(),
                    value: val.len(),
                })));
            }
            co.prefix = Prefix::of(name);
            name_value = Some((name, val));
        } else if name.eq_ignore_ascii_case(b"secure") {
            if !source.secure() {
                return Ok(Parsed::Dropped(Some(Said::NotSecure)));
            }
            co.secure = true;
        } else if name.eq_ignore_ascii_case(b"httponly") {
            co.http_only = true;
        } else if sep {
            if name.eq_ignore_ascii_case(b"path") {
                path = val;
            } else if name.eq_ignore_ascii_case(b"domain") {
                if !val.is_empty() {
                    match domain_attribute(val, &mut host, suffixes.is_some()) {
                        Some(tailmatch) => {
                            domain = val.strip_prefix(b".").unwrap_or(val);
                            co.tailmatch |= tailmatch;
                        }
                        None => {
                            return Ok(Parsed::Dropped(Some(Said::BadDomain(
                                val.strip_prefix(b".").unwrap_or(val),
                            ))));
                        }
                    }
                }
            } else if name.eq_ignore_ascii_case(b"max-age") && !val.is_empty() {
                co.expires = capped(max_age(val, now), now);
            } else if name.eq_ignore_ascii_case(b"expires")
                && !val.is_empty()
                && co.expires == 0
                && val.len() < MAX_DATE_LEN
            {
                // A date that cannot be read leaves a session cookie.
                co.expires = match crate::date::parse(val) {
                    Ok(0) => 1,
                    Ok(date) => date,
                    Err(_) => 0,
                };
                co.expires = capped(co.expires, now);
            }
        }
        match rest.first() {
            Some(b';') => rest = &rest[1..],
            _ => break,
        }
    }
    let Some((name, val)) = name_value else {
        return Ok(Parsed::Dropped(None));
    };
    co.name = copy(name)?;
    co.value = copy(val)?;
    // Without a path, the request's, up to its last slash.
    let path = if !path.is_empty() {
        Some(path)
    } else {
        default_path.map(|p| match p.iter().rposition(|&b| b == b'/') {
            Some(at) => &p[..=at],
            None => p,
        })
    };
    co.path = path.map(sanitized_path).transpose()?;
    co.domain = if !domain.is_empty() {
        Some(copy(domain)?)
    } else {
        host.map(copy).transpose()?
    };
    Ok(Parsed::Cookie(co))
}

/// Whether a `Domain` attribute may be set from `host` (`parse_domain`),
/// and whether it then goes to the hosts below it: none where it may
/// not. `listed`: public suffixes are checked later; without them, the
/// domain needs a dot not at its end, or to be `localhost`, and a host
/// it is not for is forgotten for the cookie's default.
fn domain_attribute(val: &[u8], host: &mut Option<&[u8]>, listed: bool) -> Option<bool> {
    let val = val.strip_prefix(b".").unwrap_or(val);
    if !listed && bad_domain(val) {
        *host = Some(b":");
    }
    let Some(h) = *host else {
        return Some(!is_ip_address(val));
    };
    if is_ip_address(h) {
        (val == h).then_some(false)
    } else {
        tailmatch(val, h).then_some(true)
    }
}

/// Whether `domain` may not have cookies set for it, lacking a list of
/// public suffixes (`bad_domain`).
fn bad_domain(domain: &[u8]) -> bool {
    if domain.eq_ignore_ascii_case(b"localhost") {
        return false;
    }
    // A dot, but not at the end.
    !domain
        .iter()
        .position(|&b| b == b'.')
        .is_some_and(|at| domain.len() - at > 1)
}

/// Whether `co` is set on a public suffix from a host that may not set
/// it there (`is_public_suffix`), `host` being none for a file's. One
/// that is allowed there goes to that domain alone.
fn on_public_suffix(
    co: &mut Cookie,
    host: Option<&[u8]>,
    suffixes: &dyn PublicSuffixes,
) -> Option<bool> {
    let domain = co.domain.as_deref()?;
    if is_ip_address(domain) {
        return None;
    }
    let trimmed = |s: &[u8]| -> ([u8; 255], usize, bool) {
        let s = s.strip_suffix(b".").unwrap_or(s);
        let mut low = [0u8; 255];
        if s.len() >= 256 {
            return (low, 0, false);
        }
        for (d, s) in low.iter_mut().zip(s) {
            *d = s.to_ascii_lowercase();
        }
        (low, s.len(), true)
    };
    let (cookie_low, clen, cfits) = trimmed(domain);
    let (host_low, hlen, hfits) = trimmed(host.unwrap_or_default());
    let mut acceptable = false;
    let problem = cfits && hfits && !suffixes.available();
    if cfits && hfits && !problem {
        let cookie_low = &cookie_low[..clen];
        match host {
            Some(host) => {
                acceptable = suffixes.accepts(&host_low[..hlen], cookie_low);
                // Allowed on a public suffix, it is for that host alone.
                if acceptable
                    && co.tailmatch
                    && domain.eq_ignore_ascii_case(host)
                    && suffixes.is_public_suffix(cookie_low)
                {
                    co.tailmatch = false;
                }
            }
            None => {
                acceptable = true;
                if suffixes.is_public_suffix(cookie_low) {
                    co.tailmatch = false;
                }
            }
        }
    }
    (!acceptable).then_some(problem)
}

/// `Max-Age`, as the time it gives (`parse_maxage`): a number that
/// cannot be read expires the cookie at once.
fn max_age(val: &[u8], now: i64) -> i64 {
    let val = val.strip_prefix(b"\"").unwrap_or(val);
    match number(val) {
        Number::Overflow => i64::MAX,
        Number::None => 1,
        Number::Ok(0) => 1,
        Number::Ok(n) if i64::MAX - now < n => i64::MAX,
        Number::Ok(n) => n + now,
    }
}

/// No cookie lasts beyond 400 days, rounded to a minute for tests'
/// sake (`cap_expires`).
fn capped(expires: i64, now: i64) -> i64 {
    if expires != 0 && i64::MAX - MAX_AGE - 30 > now {
        let cap = now + MAX_AGE;
        if expires > cap {
            return (cap + 30) / 60 * 60;
        }
    }
    expires
}

enum Number {
    Ok(i64),
    None,
    Overflow,
}

/// The decimal number `s` starts with (`curlx_str_number`).
fn number(s: &[u8]) -> Number {
    let digits = s.iter().take_while(|b| b.is_ascii_digit());
    let mut n: i64 = 0;
    let mut any = false;
    for &d in digits {
        any = true;
        n = match n
            .checked_mul(10)
            .and_then(|n| n.checked_add(i64::from(d - b'0')))
        {
            Some(n) => n,
            None => return Number::Overflow,
        };
    }
    if any { Number::Ok(n) } else { Number::None }
}

/// A cookie path as stored (`sanitize_cookie_path`): out of the quotes
/// some sites put it in, `/` for one that does not start with a slash,
/// and without a trailing slash.
fn sanitized_path(path: &[u8]) -> Result<Vec<u8>, OutOfMemory> {
    let mut path = path;
    if let Some(rest) = path.strip_prefix(b"\"") {
        path = rest.strip_suffix(b"\"").unwrap_or(rest);
    }
    if path.first() != Some(&b'/') {
        return copy(b"/");
    }
    if path.len() > 1 {
        path = path.strip_suffix(b"/").unwrap_or(path);
    }
    copy(path)
}

/// Whether a cookie for `domain` goes to `host` (`cookie_tailmatch`):
/// the same name, or one that ends in `.` and it, in any case.
fn tailmatch(domain: &[u8], host: &[u8]) -> bool {
    let Some(at) = host.len().checked_sub(domain.len()) else {
        return false;
    };
    host[at..].eq_ignore_ascii_case(domain) && (at == 0 || host[at - 1] == b'.')
}

/// Whether a cookie for `cookie_path` goes to a request for `path`
/// (`pathmatch`, RFC 6265 5.1.4): the same, or below it.
fn path_matches(cookie_path: &[u8], path: &[u8]) -> bool {
    if cookie_path.len() == 1 {
        return true;
    }
    let path = if path.first() == Some(&b'/') {
        path
    } else {
        b"/"
    };
    path.starts_with(cookie_path)
        && (path.len() == cookie_path.len() || path[cookie_path.len()] == b'/')
}

/// The order a request sends its cookies in (`cookie_sort`): longest
/// path first, then longest domain, then longest name, then newest.
fn send_order(a: &Cookie, b: &Cookie) -> Ordering {
    let len = |v: &Option<Vec<u8>>| v.as_ref().map_or(0, Vec::len);
    len(&b.path)
        .cmp(&len(&a.path))
        .then(len(&b.domain).cmp(&len(&a.domain)))
        .then(b.name.len().cmp(&a.name.len()))
        .then(b.created.cmp(&a.created))
}

/// Which bucket cookies for `domain` go in (`cookiehash`): one for
/// addresses and for none, else by the last two labels of the name, in
/// any case.
fn bucket(domain: Option<&[u8]>) -> usize {
    let Some(domain) = domain.filter(|d| !is_ip_address(d)) else {
        return 0;
    };
    let top = match domain.iter().rposition(|&b| b == b'.') {
        Some(last) => match domain[..last].iter().rposition(|&b| b == b'.') {
            Some(first) => &domain[first + 1..],
            None => domain,
        },
        None => domain,
    };
    // `cookie_hash_domain`, with C's `size_t`. A byte past ASCII is
    // taken as unsigned, as C's `char` is on this platform.
    let mut h: u64 = 5381;
    for &b in top {
        h = h.wrapping_add(h << 5);
        h ^= u64::from(b.to_ascii_uppercase());
    }
    (h % BUCKETS as u64) as usize
}

/// Whether `s` holds a control byte, which some servers refuse a request
/// over (`invalid_octets`).
fn invalid_octets(s: &[u8]) -> bool {
    s.iter().any(|&b| b < 0x20 || b == 0x7f)
}

/// Whether `field` is how `word` starts, as C's `strncmp` with the
/// field's length reads it.
fn is_prefix_of(field: &[u8], word: &[u8]) -> bool {
    word.starts_with(field)
}

fn is_prefix_of_ignore_case(field: &[u8], word: &[u8]) -> bool {
    field.len() <= word.len() && word[..field.len()].eq_ignore_ascii_case(field)
}

fn strip_prefix_ignore_case<'a>(line: &'a [u8], prefix: &[u8]) -> Option<&'a [u8]> {
    (line.len() >= prefix.len() && line[..prefix.len()].eq_ignore_ascii_case(prefix))
        .then(|| &line[prefix.len()..])
}

/// `s` up to a zero byte, as C reads a string.
fn until_zero(s: &[u8]) -> &[u8] {
    s.split(|&b| b == 0).next().unwrap_or_default()
}

fn is_blank(b: u8) -> bool {
    b == b' ' || b == b'\t'
}

fn trim_start(s: &[u8]) -> &[u8] {
    let start = s.iter().position(|&b| !is_blank(b)).unwrap_or(s.len());
    &s[start..]
}

fn trim(s: &[u8]) -> &[u8] {
    let s = trim_start(s);
    let end = s.iter().rposition(|&b| !is_blank(b)).map_or(0, |p| p + 1);
    &s[..end]
}

fn copy(s: &[u8]) -> Result<Vec<u8>, OutOfMemory> {
    let mut v = Vec::new();
    v.try_extend_from_slice(s)?;
    Ok(v)
}
