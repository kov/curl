/// The names of a mask's bits: combinations first, then single bits,
/// and the name of none last.
pub(crate) type Bits = &'static [(&'static str, u64)];

/// `CURLAUTH_*` bits.
const AUTH_BASIC: u64 = 1;
const AUTH_DIGEST: u64 = 1 << 1;
const AUTH_DIGEST_IE: u64 = 1 << 4;
const AUTH_BEARER: u64 = 1 << 6;
const AUTH_AWS_SIGV4: u64 = 1 << 7;
const AUTH_HTTPSIG: u64 = 1 << 8;
const AUTH_ONLY: u64 = 1 << 31;
/// The low 32 bits but `CURLAUTH_DIGEST_IE` and `CURLAUTH_HTTPSIG`.
const AUTH_ANY: u64 = 0xffff_feef;

/// `setopt_nv_CURLAUTH`.
pub(crate) const AUTH: Bits = &[
    ("CURLAUTH_ANY", AUTH_ANY),
    ("CURLAUTH_ANYSAFE", AUTH_ANY & !AUTH_BASIC),
    ("CURLAUTH_BASIC", AUTH_BASIC),
    ("CURLAUTH_DIGEST", AUTH_DIGEST),
    ("CURLAUTH_GSSNEGOTIATE", 1 << 2),
    ("CURLAUTH_NTLM", 1 << 3),
    ("CURLAUTH_DIGEST_IE", AUTH_DIGEST_IE),
    ("CURLAUTH_ONLY", AUTH_ONLY),
    ("CURLAUTH_NONE", 0),
];

/// The `CURLAUTH_*` mask C's tool passes for `methods`: the methods this
/// library lacks stand for every bit `CURLAUTH_ANY` has beside those it
/// names, as only `--anyauth` asks for them.
pub(crate) fn auth_mask(methods: AuthMethods) -> u64 {
    let named = [
        (AuthMethods::BASIC, AUTH_BASIC),
        (AuthMethods::DIGEST, AUTH_DIGEST),
        (AuthMethods::BEARER, AUTH_BEARER),
        (AuthMethods::AWS_SIGV4, AUTH_AWS_SIGV4),
        (AuthMethods::HTTPSIG, AUTH_HTTPSIG),
        (AuthMethods::ONLY, AUTH_ONLY),
    ];
    let mut mask = 0;
    for (method, bit) in named {
        if methods.contains(method) {
            mask |= bit;
        }
    }
    if methods.contains(AuthMethods::OTHER) {
        mask |= AUTH_ANY & !named.iter().fold(0, |all, (_, bit)| all | bit);
    }
    mask
}

/// What a pointer option points at, as the line about it says.
#[derive(Clone, Copy)]
pub(crate) enum Pointer {
    Function,
    Object,
}

/// The program, as the transfers set it up (C's `easysrc_*` lists).
#[derive(Debug, Default)]
pub(crate) struct Source {
    /// Variables declared (`easysrc_decl`).
    decl: Vec<Vec<u8>>,
    /// Lists and the like built (`easysrc_data`).
    data: Vec<Vec<u8>>,
    /// The calls; an empty line is a blank line (`easysrc_code`).
    code: Vec<Vec<u8>>,
    /// The options set that no source is written for, since the last
    /// perform (`easysrc_toohard`).
    too_hard: Vec<Vec<u8>>,
    /// What is freed at the end (`easysrc_clean`).
    clean: Vec<Vec<u8>>,
    /// The `curl_mime` variables made, and the lists.
    mimes: u32,
    slists: u32,
    /// A transfer was performed and nothing set since: the next call
    /// resets the handle first, as the tool uses a new handle for each
    /// transfer where the program uses one.
    pending_reset: bool,
}

/// Which list a line goes to.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Section {
    Decl,
    Data,
    Code,
    TooHard,
    Clean,
}

/// `parts`, joined.
fn joined(parts: &[&[u8]]) -> Result<Vec<u8>, OutOfMemory> {
    let mut line = Vec::new();
    line.try_reserve_exact(parts.iter().map(|p| p.len()).sum())
        .map_err(|_| OutOfMemory)?;
    for part in parts {
        line.try_extend_from_slice(part)?;
    }
    Ok(line)
}

/// `n` in decimal.
fn decimal(n: impl std::fmt::Display) -> Result<String, OutOfMemory> {
    try_format(format_args!("{n}"))
}

/// `s` as a C string's contents (`c_escape`): tabs, returns, newlines,
/// question marks (no trigraph is made by accident), quotes and
/// backslashes escaped, and any other byte not printable in octal before
/// a hexadecimal digit, else in hexadecimal; cut at 2000 bytes.
pub(crate) fn c_escape(s: &[u8]) -> Result<Vec<u8>, OutOfMemory> {
    let (s, cut) = match s.get(..MAX_STRING) {
        Some(head) if s.len() > MAX_STRING => (head, true),
        _ => (s, false),
    };
    let mut out = Vec::new();
    out.try_reserve_exact(s.len()).map_err(|_| OutOfMemory)?;
    for (i, &b) in s.iter().enumerate() {
        let escaped: &[u8] = match b {
            b'\t' => b"\\t",
            b'\r' => b"\\r",
            b'\n' => b"\\n",
            b'?' => b"\\?",
            b'"' => b"\\\"",
            b'\\' => b"\\\\",
            0x20..=0x7e => {
                out.try_push(b)?;
                continue;
            }
            _ => {
                let code = if s.get(i + 1).is_some_and(u8::is_ascii_hexdigit) {
                    try_format(format_args!("\\{b:03o}"))?
                } else {
                    try_format(format_args!("\\x{b:02x}"))?
                };
                out.try_extend_from_slice(code.as_bytes())?;
                continue;
            }
        };
        out.try_extend_from_slice(escaped)?;
    }
    if cut {
        out.try_extend_from_slice(b"...")?;
    }
    Ok(out)
}

/// `s` up to its first zero byte, as C reads a string.
pub(crate) fn c_string(s: &[u8]) -> &[u8] {
    s.split(|&b| b == 0).next().unwrap_or_default()
}

impl Source {
    /// A program that makes its handle (`easysrc_init`).
    pub(crate) fn new() -> Result<Source, OutOfMemory> {
        let mut source = Source::default();
        source.add(Section::Code, b"curl = curl_easy_init();")?;
        Ok(source)
    }

    /// Add `line` to `section` (`easysrc_add`); a call after a perform
    /// resets the handle first.
    fn add(&mut self, section: Section, line: &[u8]) -> Result<(), OutOfMemory> {
        if section == Section::Code && std::mem::take(&mut self.pending_reset) {
            self.add(Section::Code, b"curl_easy_reset(curl);")?;
        }
        let list = match section {
            Section::Decl => &mut self.decl,
            Section::Data => &mut self.data,
            Section::Code => &mut self.code,
            Section::TooHard => &mut self.too_hard,
            Section::Clean => &mut self.clean,
        };
        let mut owned = Vec::new();
        owned.try_extend_from_slice(line)?;
        list.try_push(owned)?;
        Ok(())
    }

    fn add_parts(&mut self, section: Section, parts: &[&[u8]]) -> Result<(), OutOfMemory> {
        let line = joined(parts)?;
        self.add(section, &line)
    }

    /// Add a call to the program.
    pub(crate) fn code(&mut self, parts: &[&[u8]]) -> Result<(), OutOfMemory> {
        self.add_parts(Section::Code, parts)
    }

    /// Perform the transfer set up (`easysrc_perform`): the options no
    /// source was written for said first.
    pub(crate) fn perform(&mut self) -> Result<(), OutOfMemory> {
        if !self.too_hard.is_empty() {
            self.add(Section::Code, b"")?;
            for line in TOO_HARD {
                self.add(Section::Code, line.as_bytes())?;
            }
            for line in std::mem::take(&mut self.too_hard) {
                self.add(Section::Code, &line)?;
            }
            self.add(Section::Code, b"")?;
            self.add(Section::Code, b"*/")?;
        }
        self.add(Section::Code, b"")?;
        self.add(Section::Code, b"result = curl_easy_perform(curl);")?;
        self.add(Section::Code, b"")?;
        self.pending_reset = true;
        Ok(())
    }

    /// Free the handle (`easysrc_cleanup`): nothing follows to reset it
    /// for.
    pub(crate) fn cleanup(&mut self) -> Result<(), OutOfMemory> {
        self.pending_reset = false;
        self.add(Section::Code, b"curl_easy_cleanup(curl);")?;
        self.add(Section::Code, b"curl = NULL;")
    }

    /// A list of `items` (`libcurl_generate_slist`): the number of its
    /// variable.
    pub(crate) fn slist<'i>(
        &mut self,
        items: impl IntoIterator<Item = &'i [u8]>,
    ) -> Result<u32, OutOfMemory> {
        self.slists += 1;
        let n = decimal(self.slists)?;
        let n = n.as_bytes();
        self.add_parts(Section::Decl, &[b"struct curl_slist *slist", n, b";"])?;
        self.add_parts(Section::Data, &[b"slist", n, b" = NULL;"])?;
        self.add_parts(Section::Clean, &[b"curl_slist_free_all(slist", n, b");"])?;
        self.add_parts(Section::Clean, &[b"slist", n, b" = NULL;"])?;
        for item in items {
            let escaped = c_escape(c_string(item))?;
            self.add_parts(
                Section::Data,
                &[
                    b"slist",
                    n,
                    b" = curl_slist_append(slist",
                    n,
                    b", \"",
                    &escaped,
                    b"\");",
                ],
            )?;
        }
        Ok(self.slists)
    }

    /// A `curl_mime` (`libcurl_generate_mime`): the number of its
    /// variable. Its parts are added by the caller, declared here if it
    /// has any.
    pub(crate) fn mime(&mut self, has_parts: bool) -> Result<u32, OutOfMemory> {
        self.mimes += 1;
        let n = decimal(self.mimes)?;
        let n = n.as_bytes();
        self.add_parts(Section::Decl, &[b"curl_mime *mime", n, b";"])?;
        self.add_parts(Section::Data, &[b"mime", n, b" = NULL;"])?;
        self.add_parts(Section::Code, &[b"mime", n, b" = curl_mime_init(curl);"])?;
        self.add_parts(Section::Clean, &[b"curl_mime_free(mime", n, b");"])?;
        self.add_parts(Section::Clean, &[b"mime", n, b" = NULL;"])?;
        if has_parts {
            self.add_parts(Section::Decl, &[b"curl_mimepart *part", n, b";"])?;
        }
        Ok(self.mimes)
    }

    /// Write the program (`dumpeasysrc`).
    fn dump(&self, out: &mut dyn FnMut(&[u8])) {
        for line in HEAD {
            out(line.as_bytes());
            out(b"\n");
        }
        for line in &self.decl {
            out(b"  ");
            out(line);
            out(b"\n");
        }
        if !self.data.is_empty() {
            out(b"\n");
            for line in &self.data {
                out(b"  ");
                out(line);
                out(b"\n");
            }
        }
        out(b"\n");
        for line in &self.code {
            if !line.is_empty() {
                out(b"  ");
                out(line);
            }
            out(b"\n");
        }
        for line in &self.clean {
            out(b"  ");
            out(line);
            out(b"\n");
        }
        for line in END {
            out(line.as_bytes());
            out(b"\n");
        }
    }

    /// End the program and write it to `out`. For tests.
    #[cfg(test)]
    pub(crate) fn finish_into(mut self, out: &mut Vec<u8>) {
        self.cleanup().unwrap();
        self.dump(&mut |b| out.extend_from_slice(b));
    }

    /// End the program and write it to `name`, standard output for `-`;
    /// a file that cannot be made is warned of.
    pub(crate) fn finish(
        mut self,
        name: &[u8],
        stdout: &Stdout,
        msgs: &Messages,
    ) -> Result<(), OutOfMemory> {
        self.cleanup()?;
        if name == b"-" {
            // A failure to write shows when standard output is flushed.
            self.dump(&mut |bytes| {
                stdout.fwrite(bytes);
            });
            return Ok(());
        }
        let opened = curl_os::fs::with_c_name(name, |path| {
            curl_os::fs::open_write(path, curl_os::fs::Keep::Nothing, 0o666)
        });
        match opened {
            Ok(file) => {
                let mut file = crate::stdio::Stdio::new(file);
                self.dump(&mut |bytes| {
                    file.fwrite(bytes);
                });
                // A failed write goes unsaid, as in C.
                drop(crate::stdio::close(file));
            }
            Err(_) => msgs.warn(&[b"Failed to open ", name, b" to write libcurl code"]),
        }
        Ok(())
    }
}

/// The options of one transfer, set as C's tool sets them, each with
/// the `curl_easy_setopt` call `--libcurl` writes for it
/// (`tool_setopt_*`). A value is applied first and written only once it
/// is taken, as C writes only a call that succeeded.
pub(crate) struct Setopt<'a> {
    options: &'a mut Options,
    source: Option<&'a mut Source>,
}

fn oom(_: OutOfMemory) -> ErrorKind {
    ErrorKind::OutOfMemory
}

impl<'a> Setopt<'a> {
    /// Set `easy`'s options, written to `source` if there is one.
    pub(crate) fn new(easy: &'a mut Easy, source: Option<&'a mut Source>) -> Setopt<'a> {
        Setopt {
            options: easy.options_mut(),
            source,
        }
    }

    /// Apply `apply`; the program, if one is written.
    fn apply(
        &mut self,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<Option<&mut Source>, ErrorKind> {
        apply(self.options)?;
        Ok(self.source.as_deref_mut())
    }

    /// A `long` option (`tool_setopt_long`): written unless it is the
    /// option's default.
    pub(crate) fn long(
        &mut self,
        name: &'static str,
        value: i64,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        let default = NONZERO_DEFAULTS
            .iter()
            .find(|(n, _)| *n == name)
            .map_or(0, |&(_, v)| v);
        if value != default {
            long_line(source, name, value).map_err(oom)?;
        }
        Ok(())
    }

    /// A `curl_off_t` option (`tool_setopt_offt`): written unless 0.
    pub(crate) fn offt(
        &mut self,
        name: &'static str,
        value: i64,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        if value != 0 {
            let n = decimal(value).map_err(oom)?;
            source
                .code(&[
                    b"curl_easy_setopt(curl, ",
                    name.as_bytes(),
                    b", (curl_off_t)",
                    n.as_bytes(),
                    b");",
                ])
                .map_err(oom)?;
        }
        Ok(())
    }

    /// A string option (`tool_setopt_str`): written if set, up to its
    /// first zero byte as C reads it.
    pub(crate) fn str(
        &mut self,
        name: &'static str,
        value: Option<&[u8]>,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        self.bytes(name, value.map(c_string), apply)
    }

    /// `CURLOPT_POSTFIELDS`: written whole, as C gives its length.
    pub(crate) fn postfields(
        &mut self,
        value: &[u8],
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        self.bytes("CURLOPT_POSTFIELDS", Some(value), apply)
    }

    fn bytes(
        &mut self,
        name: &'static str,
        value: Option<&[u8]>,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        if let Some(value) = value {
            let escaped = c_escape(value).map_err(oom)?;
            source
                .code(&[
                    b"curl_easy_setopt(curl, ",
                    name.as_bytes(),
                    b", \"",
                    &escaped,
                    b"\");",
                ])
                .map_err(oom)?;
        }
        Ok(())
    }

    /// A pointer option, said among those no source is written for
    /// (`tool_setopt_ptr`).
    pub(crate) fn ptr(
        &mut self,
        name: &'static str,
        to: Pointer,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        let what: &[u8] = match to {
            Pointer::Function => b" was set to a function pointer",
            Pointer::Object => b" was set to an object pointer",
        };
        source
            .add_parts(Section::TooHard, &[name.as_bytes(), what])
            .map_err(oom)
    }

    /// A list option (`tool_setopt_slist`): written if the list has
    /// items.
    pub(crate) fn slist(
        &mut self,
        name: &'static str,
        items: &[&[u8]],
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        if items.is_empty() {
            return Ok(());
        }
        let n = source.slist(items.iter().copied()).map_err(oom)?;
        let n = decimal(n).map_err(oom)?;
        source
            .code(&[
                b"curl_easy_setopt(curl, ",
                name.as_bytes(),
                b", slist",
                n.as_bytes(),
                b");",
            ])
            .map_err(oom)
    }

    /// An option of named values (`tool_setopt_enum`): written by name
    /// unless 0.
    pub(crate) fn enumerated(
        &mut self,
        name: &'static str,
        names: Names,
        value: i64,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        if value == 0 {
            return Ok(());
        }
        match names.iter().find(|&&(_, v)| v == value) {
            Some((symbol, _)) => source
                .code(&[
                    b"curl_easy_setopt(curl, ",
                    name.as_bytes(),
                    b", (long)",
                    symbol.as_bytes(),
                    b");",
                ])
                .map_err(oom),
            None => long_line(source, name, value).map_err(oom),
        }
    }

    /// A mask of named bits (`tool_setopt_bitmask`): written unless 0, a
    /// line per name that takes bits left, and the bits no name takes as
    /// a number.
    pub(crate) fn bitmask(
        &mut self,
        name: &'static str,
        bits: Bits,
        value: u64,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        if value == 0 {
            return Ok(());
        }
        bitmask_lines(source, name, bits, value).map_err(oom)
    }

    /// `CURLOPT_MIMEPOST`, with the calls that build its tree
    /// (`tool_setopt_mimepost`).
    pub(crate) fn mimepost(
        &mut self,
        form: &crate::form::Form,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        let Some(source) = self.apply(apply)? else {
            return Ok(());
        };
        let n = form.libcurl(source).map_err(oom)?;
        let n = decimal(n).map_err(oom)?;
        source
            .code(&[
                b"curl_easy_setopt(curl, CURLOPT_MIMEPOST, mime",
                n.as_bytes(),
                b");",
            ])
            .map_err(oom)
    }

    /// An option C's tool sets with `curl_easy_setopt` itself, which the
    /// program does not show; `_why` says where.
    pub(crate) fn unwritten(
        &mut self,
        _why: &'static str,
        apply: impl FnOnce(&mut Options) -> Result<(), ErrorKind>,
    ) -> Result<(), ErrorKind> {
        apply(self.options)
    }
}

fn long_line(source: &mut Source, name: &str, value: i64) -> Result<(), OutOfMemory> {
    let n = decimal(value)?;
    source.code(&[
        b"curl_easy_setopt(curl, ",
        name.as_bytes(),
        b", ",
        n.as_bytes(),
        b"L);",
    ])
}

fn bitmask_lines(
    source: &mut Source,
    name: &str,
    bits: Bits,
    value: u64,
) -> Result<(), OutOfMemory> {
    let preamble = joined(&[b"curl_easy_setopt(curl, ", name.as_bytes(), b", "])?;
    let mut blank = Vec::new();
    blank.try_extend_from_slice(&preamble)?;
    blank.fill(b' ');
    let mut lead = &preamble[..];
    let mut rest = value;
    for &(symbol, bit) in bits {
        // Every bit of the name is among those left; a name of none is
        // always.
        if bit & !rest == 0 {
            rest &= !bit;
            let end: &[u8] = if rest != 0 { b" |" } else { b");" };
            source.code(&[lead, b"(long)", symbol.as_bytes(), end])?;
            if rest == 0 {
                return Ok(());
            }
            lead = &blank;
        }
    }
    let n = decimal(rest)?;
    source.code(&[lead, n.as_bytes(), b"UL);"])
}

