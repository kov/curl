#!/usr/bin/env python3
"""
Inventory of libcurl's option-like entry points.

Covers CURLOPT_* (easy), CURLMOPT_* and CURLMINFO_* (multi), CURLSHOPT_*
and CURL_LOCK_DATA_* (share), CURLUPART_* and CURLU_* (URL API), CURLINFO_*
(getinfo), CURLH_* (header origins) and CURLWS_* (websocket flags).

Names and structure are parsed from the public headers; numeric values are
computed by compiling a C probe with gcc against include/, so the values
are the ones a C compiler sees. Cross-checked against lib/easyoptions.c
(generated by lib/optiontable.pl from include/curl/curl.h),
include/curl/typecheck-gcc.h, docs/libcurl/opts/*.md and
docs/libcurl/symbols-in-versions.
"""

