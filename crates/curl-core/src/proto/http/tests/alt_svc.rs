//! The alt-svc cache in transfers (`lib/altsvc.c`, `url_set_conn_peer`,
//! `http_header_a`): an origin the cache knows connected to by its
//! alternative, the request naming it, and a response over HTTPS kept.

use super::*;
use crate::altsvc::{AltSvcCtrl, Versions};
use crate::save::CacheFile;
use crate::tls::fake::{self, WELCOME};

/// A temporary file of the test's, removed as it goes.
struct Temp(std::path::PathBuf);

impl Temp {
    fn new(name: &str, text: &str) -> Temp {
        let path =
            std::env::temp_dir().join(format!("curl-core-alt-svc-{name}-{}", std::process::id()));
        std::fs::write(&path, text).unwrap();
        Temp(path)
    }

    fn name(&self) -> &[u8] {
        self.0.as_os_str().as_encoded_bytes()
    }

    fn text(&self) -> String {
        std::fs::read_to_string(&self.0).unwrap()
    }
}

impl Drop for Temp {
    fn drop(&mut self) {
        let _gone = std::fs::remove_file(&self.0);
    }
}

/// A multi whose network knows `alt.example` as 127.0.0.1, where a server
/// says `replies` in turn, and nothing of `origin.example`: a transfer to
/// the origin gets through only by its alternative.
fn alt_server(replies: &[&[u8]]) -> (Multi, Conversation) {
    let clock = ManualClock::new().unwrap();
    clock.set_unix_time(NOW);
    let at = SocketAddr::from(([127, 0, 0, 1], PORT));
    let talk = Conversation::replies(replies, false);
    let net = FakeNet::new(clock.clone())
        .with_peer(at, Peer::Accepts)
        .with_conversation(at, talk.clone())
        .with_name("alt.example", &[[127, 0, 0, 1].into()]);
    let env = Env {
        clock: Box::new(clock),
        net: Box::new(net),
        arena: ArenaPolicy::new(16, 0).unwrap(),
        waker: None,
    };
    (Multi::new(env).unwrap(), talk)
}

/// The time the tests' clock says, 2024-10-09 09:25:47 UTC.
const NOW: i64 = 1_728_465_947;

/// The cache's file, naming `alt.example` the origin's alternative.
fn cache_file(name: &str) -> Temp {
    let line =
        format!("h1 origin.example {PORT} h1 alt.example {PORT} \"20991231 00:00:00\" 0 0\n");
    Temp::new(name, &line)
}

const SAID: &[u8] = b"HTTP/1.1 200 OK\r\nAlt-Svc: h1=\"next.example:443\"; ma=60\r\n\
    Content-Length: 3\r\n\r\nok\n";

/// An `https` URL to an origin the cache knows connects to its
/// alternative, the request naming it in `Alt-Used:` and the origin in
/// `Host:`; what the response says is kept, and written to the file.
#[test]
fn an_origin_is_reached_by_its_alternative() {
    let file = cache_file("used");
    let (_backend, libraries) = super::tls::tls();
    let (mut m, talk) = alt_server(&[WELCOME, &fake::records(SAID).unwrap()]);
    let mut e = Easy::new();
    e.set_libraries(libraries);
    e.add_alt_svc_file(Some(file.name())).unwrap();
    let url = format!("https://origin.example:{PORT}/a");
    let mut ran = get_with(&mut m, e, "/a", talk, |o| {
        o.set_url(Some(url.as_bytes())).unwrap();
    });
    assert_eq!(ran.result, Ok(()));
    let request = fake::read_client(&ran.request).unwrap();
    let want = format!(
        "GET /a HTTP/1.1\r\nHost: origin.example:{PORT}\r\nUser-Agent: curl/test\r\n\
         Accept: */*\r\nAlt-Used: alt.example:{PORT}\r\n\r\n"
    );
    let request = String::from_utf8_lossy(&request);
    assert!(request.contains(&want), "{request}");
    let text = ran.seen.text();
    let connecting =
        format!("Alt-svc connecting from [h1]origin.example:{PORT} to [h1]alt.example:{PORT}\n");
    assert!(text.contains(&connecting), "{text:?}");
    assert!(text.contains(&"Added alt-svc: next.example:443 over h1\n".to_string()));
    ran.easy.save_alt_svc().unwrap();
    assert_eq!(
        file.text(),
        format!(
            "# Your alt-svc cache. https://curl.se/docs/alt-svc.html\n\
             # This file was generated by libcurl! Edit at your own risk.\n\
             h1 origin.example {PORT} h1 next.example 443 \"20241009 09:26:47\" 0 0\n"
        )
    );
}

/// The application's own `Alt-Used:` goes in the library's place.
#[test]
fn the_application_s_alt_used_replaces_the_library_s() {
    let file = cache_file("own");
    let (_backend, libraries) = super::tls::tls();
    let (mut m, talk) = alt_server(&[WELCOME, &fake::records(SAID).unwrap()]);
    let mut e = Easy::new();
    e.set_libraries(libraries);
    e.add_alt_svc_file(Some(file.name())).unwrap();
    let url = format!("https://origin.example:{PORT}/a");
    let ran = get_with(&mut m, e, "/a", talk, |o| {
        o.set_url(Some(url.as_bytes())).unwrap();
        o.http.headers = crate::options::UserHeaders::new([&b"Alt-Used: mine"[..]]).unwrap();
    });
    assert_eq!(ran.result, Ok(()));
    let request = String::from_utf8_lossy(&fake::read_client(&ran.request).unwrap()).into_owned();
    assert!(request.contains("\r\nAlt-Used: mine\r\n"), "{request}");
    assert_eq!(request.matches("Alt-Used").count(), 1, "{request}");
}

/// No alternative is taken for a plain `http` URL, nor for HTTP/1.0, nor
/// when the application allows no HTTP/1 alternative, nor where a
/// connect-to entry names the peer; and a field over plain HTTP is not
/// kept.
#[test]
fn an_alternative_is_taken_only_where_c_takes_one() {
    type Set = fn(&mut Easy);
    let cases: [(&str, &str, Set); 4] = [
        ("plain", "http", |_| {}),
        ("ten", "https", |e| {
            e.options_mut().http.version = crate::options::HttpVersion::Http10;
        }),
        ("noh1", "https", |e| {
            let versions = Versions {
                h1: false,
                h2: true,
                h3: true,
            };
            let ctrl = AltSvcCtrl {
                file: CacheFile::ReadWrite,
                versions,
            };
            e.enable_alt_svc(ctrl).unwrap();
        }),
        ("connect-to", "https", |e| {
            let entry = format!("origin.example:{PORT}:127.0.0.1:{PORT}");
            e.options_mut().connect_to.set([entry.as_bytes()]).unwrap();
        }),
    ];
    for (name, scheme, set) in cases {
        let file = cache_file(name);
        let (_backend, libraries) = super::tls::tls();
        let replies: Vec<Vec<u8>> = if scheme == "https" {
            vec![WELCOME.to_vec(), fake::records(SAID).unwrap()]
        } else {
            vec![SAID.to_vec()]
        };
        let replies: Vec<&[u8]> = replies.iter().map(Vec::as_slice).collect();
        let (mut m, talk) = alt_server(&replies);
        let mut e = Easy::new();
        e.set_libraries(libraries);
        e.add_alt_svc_file(Some(file.name())).unwrap();
        set(&mut e);
        let url = format!("{scheme}://origin.example:{PORT}/a");
        let mut ran = get_with(&mut m, e, "/a", talk, |o| {
            o.set_url(Some(url.as_bytes())).unwrap();
            if name == "plain" {
                // Reached, to show the field is passed over.
                let entry = format!("origin.example:{PORT}:127.0.0.1:{PORT}");
                o.connect_to.set([entry.as_bytes()]).unwrap();
            }
        });
        ran.easy.save_alt_svc().unwrap();
        if name == "plain" {
            assert_eq!(ran.result, Ok(()));
            assert!(!file.text().contains("next.example"), "{}", file.text());
        }
        let text = ran.seen.text();
        assert!(
            !text.iter().any(|l| l.starts_with("Alt-svc connecting")),
            "{name}: {text:?}"
        );
        if name == "connect-to" || name == "plain" {
            // Reached by the entry, with no `Alt-Used:`.
            assert_eq!(ran.result, Ok(()), "{name}");
            let request =
                String::from_utf8_lossy(&fake::read_client(&ran.request).unwrap()).into_owned();
            assert!(!request.contains("Alt-Used"), "{request}");
        } else {
            // The origin itself, which the network does not know.
            assert_eq!(ran.result, Err(ErrorKind::CouldntResolveHost), "{name}");
        }
    }
}

/// A read-only file is read and never written back; a copy of the
/// handle reads the file named, keeps the control, and starts without
/// the entries learnt since.
#[test]
fn a_read_only_file_is_kept_and_a_copy_reads_the_file() {
    let file = cache_file("read-only");
    let before = file.text();
    let mut e = Easy::new();
    e.enable_alt_svc(AltSvcCtrl {
        file: CacheFile::ReadOnly,
        ..AltSvcCtrl::DEFAULT
    })
    .unwrap();
    e.add_alt_svc_file(Some(file.name())).unwrap();
    let a = e.alt_svc_mut().unwrap();
    assert_eq!(a.len(), 1);
    let said = b"h1=\"later.example:1\"";
    a.parse(
        said,
        (b"other.example", 80, crate::altsvc::Alpn::H1),
        NOW,
        &mut |_| {},
    )
    .unwrap();
    let mut copy = e.try_clone().unwrap();
    let copied = copy.alt_svc().unwrap();
    assert_eq!(copied.len(), 1);
    assert_eq!(copied.ctrl().file, CacheFile::ReadOnly);
    copy.save_alt_svc().unwrap();
    e.save_alt_svc().unwrap();
    assert_eq!(file.text(), before);
    // Without a file named, nor read, nothing is written.
    let mut bare = Easy::new();
    bare.enable_alt_svc(AltSvcCtrl::DEFAULT).unwrap();
    bare.save_alt_svc().unwrap();
}

/// After a reset the file name the options held is gone, and the cache
/// is written to the file it last read (test 1908).
#[test]
fn a_reset_handle_writes_the_file_last_read() {
    let file = cache_file("reset");
    let mut e = Easy::new();
    e.add_alt_svc_file(Some(file.name())).unwrap();
    e.reset();
    assert!(e.options().http.alt_svc.file.is_none());
    e.save_alt_svc().unwrap();
    assert!(
        file.text().starts_with("# Your alt-svc cache."),
        "{}",
        file.text()
    );
}
