//! `--libcurl`: the C program a command line amounts to
//! (`src/tool_easysrc.c`, `src/tool_setopt.c`).
//!
//! The tool sets a transfer up through [`Setopt`] and nothing else: each
//! of its calls names the `curl_easy_setopt` C's tool makes, with the
//! value it passes, beside what it does to the transfer's options. So an
//! option is never set without the line `--libcurl` writes for it, and
//! the lines come in C's order because the options are set in it.

use curl_alloc::{OutOfMemory, TryVec as _, try_format};
use curl_core::easy::Easy;
use curl_core::error::ErrorKind;
use curl_core::options::{AuthMethods, Options, ProxyType};

use crate::msgs::Messages;
use crate::stdout::Stdout;

/// The program's start (`srchead`); the declarations follow.
const HEAD: &[&str] = &[
    "/********* Sample code generated by the curl command line tool **********",
    " * All curl_easy_setopt() options are documented at:",
    " * https://curl.se/libcurl/c/curl_easy_setopt.html",
    " ************************************************************************/",
    "#include <curl/curl.h>",
    "",
    "int main(int argc, char *argv[])",
    "{",
    "  CURLcode result;",
    "  CURL *curl;",
];

/// What comes before the options no source can be written for
/// (`srchard`).
const TOO_HARD: &[&str] = &[
    "/* Here is a list of options the curl code used that cannot get generated",
    "   as source easily. You may choose to either not use them or implement",
    "   them yourself.",
    "",
];

/// The program's end (`srcend`).
const END: &[&str] = &[
    "",
    "  return (int)result;",
    "}",
    "/**** End of sample code ****/",
];

/// Strings longer are cut there, and end in `...` (`c_escape`).
const MAX_STRING: usize = 2000;

/// The options whose default is not 0: a value equal to it is not
/// written (`setopt_nv_CURLNONZERODEFAULTS`).
const NONZERO_DEFAULTS: &[(&str, i64)] = &[
    ("CURLOPT_SSL_VERIFYPEER", 1),
    ("CURLOPT_SSL_VERIFYHOST", 1),
    ("CURLOPT_SSL_ENABLE_NPN", 1),
    ("CURLOPT_SSL_ENABLE_ALPN", 1),
    ("CURLOPT_TCP_NODELAY", 1),
    ("CURLOPT_PROXY_SSL_VERIFYPEER", 1),
    ("CURLOPT_PROXY_SSL_VERIFYHOST", 1),
    ("CURLOPT_SOCKS5_AUTH", 1),
    // `CURLULFLAG_SEEN`.
    ("CURLOPT_UPLOAD_FLAGS", 1 << 4),
];

